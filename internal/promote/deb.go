package promote

import (
	"context"
	"fmt"

	"github.com/openartifact/openartifact/internal/database/models"
	formatdeb "github.com/openartifact/openartifact/internal/format/deb"
)

// debPromoter promotes deb packages. A bundle item is the .deb blob; every live
// deb_packages row of the source that references it is copied into the
// destination under the same distribution and component (created there when
// missing, exactly like an upload does) together with the package's
// architecture. The Release and Packages indexes are generated by the deb
// worker, which the result asks to refresh.
type debPromoter struct{}

func (debPromoter) Format() string { return "deb" }

// debRow is a live source deb_packages row holding the item's content.
type debRow struct {
	candidate

	distID, compID string
	dist, comp     string
	arch, filename string
}

// poolPath is the pool path the package is served under ("" without a file name).
func (r *debRow) poolPath() string {
	if r.filename == "" {
		return ""
	}

	return formatdeb.GetPoolPath(r.comp, r.name, r.version, r.filename)
}

// quarantineKeys are the identifiers the pool download checks for quarantine.
func (r *debRow) quarantineKeys() []string {
	return nonEmpty(r.id, r.poolPath(), r.filename)
}

const debSourceQuery = `SELECT dp.id::text, dp.distribution_id::text, dp.component_id::text, dd.name, dc.name,
	       dp.name, dp.version, dp.arch, COALESCE(dp.filename, ''), COALESCE(dp.license, ''), b.size_bytes
	  FROM deb_packages dp
	  JOIN debian_distributions dd ON dd.id = dp.distribution_id
	  JOIN debian_components dc ON dc.id = dp.component_id
	  JOIN blobs b ON b.id = dp.blob_id
	 WHERE dp.repository_id = $1 AND dp.deleted_at IS NULL AND b.sha256 = $2
	 ORDER BY dp.created_at, dp.id`

// debSameCoords is the live unique key of a deb package (the component stands
// for its distribution too), spelled with names so it matches across repositories.
const debSameCoords = `dd.name = $2 AND dc.name = $3 AND d.name = $4 AND d.version = $5 AND d.arch = $6`

// debDestinationQuery returns the id, content digest and size of every live destination row
// at the package's coordinates, and of every one that has the same pool file
// name: the pool resolves a download by file name only, so one name must not
// stand for two contents.
const debDestinationQuery = `SELECT d.id::text, db.sha256, db.size_bytes, d.name, d.version, COALESCE(d.filename, ''), (` + debSameCoords + `)
	  FROM deb_packages d
	  JOIN debian_distributions dd ON dd.id = d.distribution_id
	  JOIN debian_components dc ON dc.id = d.component_id
	  JOIN blobs db ON db.id = d.blob_id
	 WHERE d.repository_id = $1 AND d.deleted_at IS NULL
	   AND ((` + debSameCoords + `) OR ($7::text <> '' AND d.filename = $7::text))`

const debEnsureDistribution = `INSERT INTO debian_distributions (repository_id, name, codename, description)
	SELECT $1::uuid, s.name, s.codename, s.description FROM debian_distributions s WHERE s.id = $2::uuid
	ON CONFLICT (repository_id, name) DO UPDATE SET name = EXCLUDED.name
	RETURNING id::text`

const debEnsureComponent = `INSERT INTO debian_components (distribution_id, name, description)
	SELECT $1::uuid, s.name, s.description FROM debian_components s WHERE s.id = $2::uuid
	ON CONFLICT (distribution_id, name) DO UPDATE SET name = EXCLUDED.name
	RETURNING id::text`

const debEnsureArchitecture = `INSERT INTO debian_architectures (distribution_id, name) VALUES ($1::uuid, $2)
	ON CONFLICT (distribution_id, name) DO NOTHING`

// debCopyQuery copies every metadata column of a package row; id, the
// timestamps and the soft-delete markers take their
// defaults.
const debCopyQuery = `INSERT INTO deb_packages (repository_id, distribution_id, component_id, blob_id, name, version, arch,
	       summary, description, license, maintainer, homepage, filename, installed_size, control_fields)
	SELECT $1::uuid, $2::uuid, $3::uuid, s.blob_id, s.name, s.version, s.arch,
	       s.summary, s.description, s.license, s.maintainer, s.homepage, s.filename, s.installed_size, s.control_fields
	  FROM deb_packages s WHERE s.id = $4::uuid AND s.deleted_at IS NULL`

// Promote implements Promoter.
func (p debPromoter) Promote(ctx context.Context, tx Tx, req Request) (*Result, error) {
	rows, err := p.sources(ctx, tx, req)
	if err != nil {
		return nil, err
	}

	res := &Result{}

	for _, row := range narrowRows(rows, func(r *debRow) candidate { return r.candidate }, req.Path) {
		if err := p.promoteRow(ctx, tx, req, row, res); err != nil {
			return nil, err
		}
	}

	if len(res.Copied) > 0 {
		res.Regen = append(res.Regen, Regen{Kind: RegenDeb, RepoID: req.Dst.ID})
	}

	return res, nil
}

// sources returns the live source rows with the item's content.
func (debPromoter) sources(ctx context.Context, tx Tx, req Request) ([]*debRow, error) {
	rows, err := tx.QueryContext(ctx, debSourceQuery, req.Src.ID, req.SHA256)
	if err != nil {
		return nil, fmt.Errorf("select deb source rows: %w", err)
	}

	defer func() { _ = rows.Close() }()

	var out []*debRow

	for rows.Next() {
		var (
			r       debRow
			license string
		)

		if err := rows.Scan(&r.id, &r.distID, &r.compID, &r.dist, &r.comp,
			&r.name, &r.version, &r.arch, &r.filename, &license, &r.size); err != nil {
			return nil, fmt.Errorf("scan deb source row: %w", err)
		}

		r.idents = nonEmpty(r.filename, r.poolPath(), r.id)
		r.licenses = nonEmpty(license)

		out = append(out, &r)
	}

	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("read deb source rows: %w", err)
	}

	if len(out) == 0 {
		return nil, ErrItemNotFound
	}

	return out, nil
}

// promoteRow copies one source row unless the destination already holds it.
func (p debPromoter) promoteRow(ctx context.Context, tx Tx, req Request, row *debRow, res *Result) error {
	art := Artifact{Name: row.name, Version: row.version, Path: row.filename, SHA256: req.SHA256, Size: row.size}
	res.QuarantineKeys = append(res.QuarantineKeys, row.quarantineKeys()...)

	dest, err := p.destination(ctx, tx, req, row)
	if err != nil {
		return err
	}

	if err := dest.replace(ctx, tx, req, models.TrashKindDeb, "deb", row.name, row.version, res); err != nil {
		return err
	}

	switch {
	case dest.same:
		res.Existing = append(res.Existing, art)
	default:
		if err := p.copyRow(ctx, tx, req, row); err != nil {
			return err
		}

		res.Copied = append(res.Copied, art)
		res.Usage.Bytes += row.size
		res.Usage.Artifacts++
		res.Licenses = append(res.Licenses, row.licenses...)
	}

	return nil
}

// destination collects what the destination holds for the source row: the
// same package at the same coordinates with the same content is same, any
// colliding row (same coordinates or same pool file name) with other content
// is a differing row.
func (debPromoter) destination(ctx context.Context, tx Tx, req Request, row *debRow) (*destCollisions, error) {
	rows, err := tx.QueryContext(ctx, debDestinationQuery,
		req.Dst.ID, row.dist, row.comp, row.name, row.version, row.arch, row.filename)
	if err != nil {
		return nil, fmt.Errorf("look up deb package in the target: %w", err)
	}

	defer func() { _ = rows.Close() }()

	c := &destCollisions{}

	for rows.Next() {
		var (
			d          destRow
			sameCoords bool
		)

		if err := rows.Scan(&d.id, &d.sha, &d.size, &d.name, &d.version, &d.path, &sameCoords); err != nil {
			return nil, fmt.Errorf("scan deb target row: %w", err)
		}

		switch {
		case d.sha != req.SHA256:
			c.differing = append(c.differing, d)
		case sameCoords:
			c.same = true
		}
	}

	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("read deb target rows: %w", err)
	}

	return c, nil
}

// copyRow writes the package row into the destination, creating the
// distribution, component and architecture it lives in when they are missing.
func (debPromoter) copyRow(ctx context.Context, tx Tx, req Request, row *debRow) error {
	var distID, compID string

	if err := tx.QueryRowContext(ctx, debEnsureDistribution, req.Dst.ID, row.distID).Scan(&distID); err != nil {
		return fmt.Errorf("get or create deb distribution %q in the target: %w", row.dist, err)
	}

	if err := tx.QueryRowContext(ctx, debEnsureComponent, distID, row.compID).Scan(&compID); err != nil {
		return fmt.Errorf("get or create deb component %q in the target: %w", row.comp, err)
	}

	if _, err := tx.ExecContext(ctx, debEnsureArchitecture, distID, row.arch); err != nil {
		return fmt.Errorf("get or create deb architecture %q in the target: %w", row.arch, err)
	}

	res, err := tx.ExecContext(ctx, debCopyQuery, req.Dst.ID, distID, compID, row.id)
	if err != nil {
		return fmt.Errorf("copy deb package row into the target: %w", err)
	}

	if n, err := res.RowsAffected(); err == nil && n == 0 {
		return fmt.Errorf("copy deb package row into the target: %w", ErrItemNotFound)
	}

	return nil
}
