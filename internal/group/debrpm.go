// ErrDistNotFound is returned by MetadataGenerator.Generate when no member of a
// Debian group has the requested distribution.
var ErrDistNotFound = errors.New("group: distribution not found in any member")

// MetadataGenerator produces and invalidates the merged metadata of deb and rpm
// groups (the worker.GroupMetadataWorker).
type MetadataGenerator interface {
	// Generate synchronously (re)generates the metadata of the group. dist, for
	// a Debian group, is a distribution the request asked for: it is added to
	// the group's served set when some member has it, ErrDistNotFound
	// otherwise.
	//
	// readable are the IDs of the members the caller may read: the metadata a
	// caller gets lists only their packages.
	Generate(ctx context.Context, groupID, dist string, readable []string) error
	// Scope names where the metadata for a caller who can read the members
	// with these IDs is stored: "" when that is every member of the group (one
	// index shared by all such callers), a path prefix of its own otherwise. ok
	// is false when none of them is a live member.
	Scope(ctx context.Context, groupID string, readable []string) (scope string, ok bool, err error)
	// Refresh schedules a coalesced regeneration; it is a no-op while one is
	// already pending or running.
	Refresh(groupID string)
}

// WithMetadata enables deb and rpm groups: their merged metadata is read from
// the blob store (blobs) and generated by gen.
func (h *Handler) WithMetadata(blobs storage.BlobStore, gen MetadataGenerator) *Handler {
	h.blobs, h.metadata = blobs, gen

	return h
}

// Metadata cache lifetimes, as the hosted deb/rpm handlers.
const (
	debMetadataMaxAge = 300
	rpmMetadataMaxAge = 300
	// repodata files are named by their checksum and never change.
	rpmRepodataMaxAge = 86400
	publicKeyMaxAge   = 86400

	// generationTimeout bounds the on-demand generation a first request waits
	// for; the work is not lost when it is exceeded (proxy members' upstream
	// downloads stay cached) and a retry resumes from there.
	generationTimeout = 2 * time.Minute
)

// serveDebRPM answers a request of a deb or rpm group: the merged metadata
// from the group's own generated rows, and package files from the member the
// merged index lists them for. readable are the members the caller may read.
func (h *Handler) serveDebRPM(w http.ResponseWriter, r *http.Request, grp *models.Repository, readable []*models.Repository, relPath string, be Backend) {
	if h.metadata == nil || h.blobs == nil {
		http.Error(w, "deb and rpm groups are not available", http.StatusNotImplemented)
		return
	}

	// The merged index lists every member's packages; a caller who can read
	// none of them has no business with it.
	if len(readable) == 0 {
		http.NotFound(w, r)
		return
	}

	kind := classifyDebRPM(grp.Format, relPath)
	if kind.class == classNone {
		http.NotFound(w, r)
		return
	}

	// What a caller is served lists only the members they can read, so each
	// distinct set of readable members has an index (and signature) of its own;
	// callers who can read every member share the group's.
	ids := make([]string, len(readable))
	for i, m := range readable {
		ids[i] = m.ID
	}

	scope, ok, err := h.metadata.Scope(r.Context(), grp.ID, ids)
	if err != nil {
		h.log.Errorw("failed to scope group metadata", "group", grp.Name, "error", err)
		http.Error(w, "internal error", http.StatusInternalServerError)

		return
	}

	if !ok {
		http.NotFound(w, r)
		return
	}

	switch kind.class {
	case classMetadata:
		if relPath == "public.key" {
			scope = "" // the key is the same for every variant
		}

		h.serveGroupMetadata(w, r, grp, kind, relPath, scope, ids)
	case classFile:
		h.serveGroupFile(w, r, grp, readable, scope, relPath, be)
	default:
		http.NotFound(w, r)
	}
}

type pathClass int

const (
	classNone pathClass = iota
	classMetadata
	classFile
)

// debRPMPath is the classification of a request path of a deb or rpm group.
type debRPMPath struct {
	class pathClass
	// dist is the Debian distribution of a dists/ path, "" otherwise.
	dist string
	// anchor marks the files a client reads first (a Debian Release,
	// InRelease or Release.gpg, an RPM repomd.xml or its signature): a miss
	// on one generates the metadata of the caller's variant.
	anchor bool
	// gunzip marks a plain Packages file, served by decompressing Packages.gz.
	gunzip      bool
	contentType string
	maxAge      int
}

func classifyDebRPM(format, relPath string) debRPMPath {
	if relPath == "public.key" {
		return debRPMPath{class: classMetadata, contentType: "application/pgp-keys", maxAge: publicKeyMaxAge}
	}

	if format == "deb" {
		return classifyDeb(relPath)
	}

	return classifyRPM(relPath)
}

func classifyDeb(relPath string) debRPMPath {
	if strings.HasPrefix(relPath, "pool/") {
		if !pathseg.Path(relPath) {
			return debRPMPath{}
		}

		return debRPMPath{class: classFile}
	}

	rest, ok := strings.CutPrefix(relPath, "dists/")
	if !ok {
		return debRPMPath{}
	}

	dist, file, ok := strings.Cut(rest, "/")
	if !ok || !pathseg.Name(dist) || !pathseg.Path(file) {
		return debRPMPath{}
	}

	p := debRPMPath{class: classMetadata, dist: dist, maxAge: debMetadataMaxAge}

	switch {
	case file == "Release" || file == "InRelease":
		p.contentType, p.anchor = "text/plain", true
	case file == "Release.gpg":
		p.contentType, p.anchor = "application/pgp-signature", true
	case strings.HasSuffix(file, "/Packages"):
		p.contentType, p.gunzip = "text/plain", true
	case strings.HasSuffix(file, "/Packages.gz"):
		p.contentType = "application/gzip"
	case strings.HasSuffix(file, "/Packages.xz"):
		p.contentType = "application/x-xz"
	default:
		return debRPMPath{}
	}

	return p
}

func classifyRPM(relPath string) debRPMPath {
	file, ok := strings.CutPrefix(relPath, "repodata/")
	if !ok {
		if !pathseg.Path(relPath) {
			return debRPMPath{}
		}

		return debRPMPath{class: classFile}
	}

	p := debRPMPath{class: classMetadata, maxAge: rpmRepodataMaxAge}

	switch {
	case file == "repomd.xml":
		p.contentType, p.maxAge, p.anchor = "application/xml", rpmMetadataMaxAge, true
	case file == "repomd.xml.asc":
		p.contentType, p.maxAge, p.anchor = "application/pgp-signature", rpmMetadataMaxAge, true
	case strings.HasSuffix(file, ".gz"):
		p.contentType = "application/x-gzip"
	case strings.HasSuffix(file, ".xz"):
		p.contentType = "application/x-xz"
	default:
		return debRPMPath{}
	}

	if !pathseg.Name(file) {
		return debRPMPath{}
	}

	return p
}

// serveGroupMetadata serves a generated metadata row of the group. A group
// whose metadata does not exist yet is generated on the spot (the request waits
// for it, bounded); one whose cached metadata is stale or past a proxy member's
// cache lifetime is served as is while a refresh runs in the background.
func (h *Handler) serveGroupMetadata(w http.ResponseWriter, r *http.Request, grp *models.Repository, p debRPMPath, relPath, scope string, readable []string) {
	if p.gunzip {
		relPath += ".gz"
	}

	key := scope + relPath

	meta, err := h.db.GetRepoMetadataByPath(r.Context(), grp.ID, key)
	if err != nil {
		h.log.Errorw("failed to query group metadata", "group", grp.Name, "path", relPath, "error", err)
		http.Error(w, "internal error", http.StatusInternalServerError)

		return
	}

	if meta == nil {
		var ok bool

		if meta, ok = h.generateOnMiss(w, r, grp, p, key, readable); !ok {
			return
		}

		h.writeGroupMetadata(w, r, grp, p, meta)

		return
	}

	h.refreshIfExpired(r.Context(), grp)
	h.writeGroupMetadata(w, r, grp, p, meta)
}

// generateOnMiss generates the group's metadata when its anchor row is absent
// and returns the requested row afterwards. ok is false once a response was
// written.
func (h *Handler) generateOnMiss(w http.ResponseWriter, r *http.Request, grp *models.Repository, p debRPMPath, key string, readable []string) (*models.RepoMetadata, bool) {
	if !h.worthGenerating(w, r, grp, p) {
		return nil, false
	}

	ctx, cancel := context.WithTimeout(r.Context(), generationTimeout)
	defer cancel()

	err := h.metadata.Generate(ctx, grp.ID, p.dist, readable)

	switch {
	case errors.Is(err, ErrDistNotFound):
		http.NotFound(w, r)
		return nil, false
	case err != nil:
		if ctx.Err() == nil {
			h.log.Errorw("group metadata generation failed", "group", grp.Name, "error", err)
		}

		// Keep going in the background so a retry finds the result.
		h.metadata.Refresh(grp.ID)

		w.Header().Set("Cache-Control", "no-store")
		w.Header().Set("Retry-After", "10")
		http.Error(w, "repository metadata is being generated", http.StatusServiceUnavailable)

		return nil, false
	}

	meta, err := h.db.GetRepoMetadataByPath(r.Context(), grp.ID, key)
	if err != nil {
		h.log.Errorw("failed to query group metadata", "group", grp.Name, "path", key, "error", err)
		http.Error(w, "internal error", http.StatusInternalServerError)

		return nil, false
	}

	if meta == nil {
		http.NotFound(w, r)
		return nil, false
	}

	return meta, true
}

// worthGenerating reports whether a metadata miss justifies generating the
// group's metadata: before its first generation always; afterwards only for a
// Debian distribution's Release files (a distribution no earlier generation
// served, which the generator checks for existence), never for another file of
// a published distribution or for a key the group does not have. A response was
// written when it returns false.
func (h *Handler) worthGenerating(w http.ResponseWriter, r *http.Request, grp *models.Repository, p debRPMPath) bool {
	st, err := h.db.GetGroupMetadataState(r.Context(), grp.ID)
	if err != nil {
		h.log.Errorw("failed to read group metadata state", "group", grp.Name, "error", err)
		http.Error(w, "internal error", http.StatusInternalServerError)

		return false
	}

	if st == nil || st.GeneratedAt == nil {
		return true
	}

	// A variant is dropped with every regeneration of the group, so its first
	// request after one finds nothing.
	if p.anchor {
		return true
	}

	http.NotFound(w, r)

	return false
}

// refreshIfExpired schedules a background regeneration when the group is
// marked stale or a proxy member's cached upstream metadata may have changed.
func (h *Handler) refreshIfExpired(ctx context.Context, grp *models.Repository) {
	st, err := h.db.GetGroupMetadataState(ctx, grp.ID)
	if err != nil {
		h.log.Warnw("failed to read group metadata state", "group", grp.Name, "error", err)
		return
	}

	if st == nil || st.Stale || (st.RefreshAfter != nil && time.Now().After(*st.RefreshAfter)) {
		h.metadata.Refresh(grp.ID)
	}
}

func (h *Handler) writeGroupMetadata(w http.ResponseWriter, r *http.Request, grp *models.Repository, p debRPMPath, meta *models.RepoMetadata) {
	etag := `"` + meta.BlobSHA256 + `"`
	if p.gunzip {
		etag = `"` + meta.BlobSHA256 + `-plain"`
	}

	if base.Revalidate(w, r, grp.Public, etag, p.maxAge) {
		return
	}

	rc, err := h.blobs.Get(r.Context(), meta.BlobSHA256)
	if err != nil {
		h.log.Errorw("failed to read group metadata blob", "group", grp.Name, "sha256", meta.BlobSHA256, "error", err)
		http.Error(w, "internal error", http.StatusInternalServerError)

		return
	}

	defer func() { base.CloseLog(rc, h.log) }()

	w.Header().Set("Content-Type", p.contentType)
	w.Header().Set("X-Content-Type-Options", "nosniff")

	var body io.Reader = rc

	if p.gunzip {
		zr, err := gzip.NewReader(rc)
		if err != nil {
			h.log.Errorw("failed to read group Packages.gz", "group", grp.Name, "sha256", meta.BlobSHA256, "error", err)
			http.Error(w, "internal error", http.StatusInternalServerError)

			return
		}

		body = zr
	} else {
		w.Header().Set("Content-Length", strconv.FormatInt(meta.BlobSize, 10))
	}

	if r.Method == http.MethodHead {
		return
	}

	if _, err := iocopy.Copy(w, body); err != nil {
		h.log.Debugw("failed to write group metadata", "group", grp.Name, "error", err)
	}
}

// serveGroupFile serves a package file from the member the merged index owns
// it for. A file the index does not list, or whose owner the caller cannot
// read, does not exist for this caller.
func (h *Handler) serveGroupFile(w http.ResponseWriter, r *http.Request, grp *models.Repository, readable []*models.Repository, scope, relPath string, be Backend) {
	// classifyDeb and classifyRPM only admit relative paths of plain segments.
	key := relPath

	owner, ok, err := h.db.GetGroupPackageOwner(r.Context(), grp.ID, scope+key)
	if err != nil {
		h.log.Errorw("failed to look up group package owner", "group", grp.Name, "path", key, "error", err)
		http.Error(w, "internal error", http.StatusInternalServerError)

		return
	}

	if !ok {
		http.NotFound(w, r)
		return
	}

	for _, m := range readable {
		if m.ID != owner {
			continue
		}

		be.ServeMember(w, r, m, memberFilePath(m, key))

		return
	}

	http.NotFound(w, r)
}

// memberFilePath is the path a member is asked for key with: a hosted member's
// router unescapes the file name itself, so it gets the escaped form the
// client sent; a proxy mirrors the path as is.
func memberFilePath(m *models.Repository, key string) string {
	if m.RepoType == "proxy" {
		return key
	}

	return (&url.URL{Path: key}).EscapedPath()
}
