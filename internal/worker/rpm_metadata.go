var errRPMLockBusy = errors.New("could not acquire advisory lock")

type RPMetadataWorker struct {
	db        sq.Database
	blobStore storage.BlobStore
	signer    gpg.Signer
	log       *logger.Logger
	reg       *metrics.Registry

	mu       sync.Mutex
	timers   map[string]*time.Timer
	debounce time.Duration
}

func NewRPMetadataWorker(db sq.Database, blobStore storage.BlobStore, signer gpg.Signer, log *logger.Logger, reg *metrics.Registry) *RPMetadataWorker {
	return &RPMetadataWorker{
		db:        db,
		blobStore: blobStore,
		signer:    signer,
		log:       log,
		reg:       reg,
		timers:    make(map[string]*time.Timer),
		debounce:  500 * time.Millisecond,
	}
}

func (w *RPMetadataWorker) NotifyStale(repoID string) {
	w.mu.Lock()
	defer w.mu.Unlock()

	if t, ok := w.timers[repoID]; ok {
		t.Stop()
	}

	var t *time.Timer

	t = time.AfterFunc(w.debounce, func() {
		defer func() {
			if r := recover(); r != nil {
				w.log.Errorw("panic in goroutine", "panic", r)
			}
		}()
		w.log.Infow("metadata regeneration triggered", "repo_id", repoID)

		start := time.Now()

		err := w.Regenerate(context.Background(), repoID)
		if w.reg != nil {
			w.reg.MetadataRegenerationDurationSeconds.WithLabelValues("rpm").Observe(time.Since(start).Seconds())
			w.reg.MetadataRegenerationsTotal.WithLabelValues("rpm").Inc()
		}

		if err != nil {
			w.log.Errorw("metadata regeneration failed", "repo_id", repoID, "error", err)
		}

		w.mu.Lock()
		if w.timers[repoID] == t {
			delete(w.timers, repoID)
		}
		w.mu.Unlock()
	})
	w.timers[repoID] = t
}

func (w *RPMetadataWorker) Stop() {
	w.mu.Lock()
	defer w.mu.Unlock()

	for id, t := range w.timers {
		t.Stop()
		delete(w.timers, id)
	}
}

// Regenerate synchronously rebuilds the repository's RPM metadata, including
// writing new metadata blobs and reclaiming superseded ones. NotifyStale is the
// debounced asynchronous entry point.
func (w *RPMetadataWorker) Regenerate(ctx context.Context, repoID string) error {
	conn := w.db.GetDB()

	var (
		baseArch      string
		metadataStale bool
	)

	err := conn.QueryRowContext(ctx, `
		SELECT base_arch, metadata_stale
		FROM rpm_repos
		WHERE repository_id = $1
	`, repoID).Scan(&baseArch, &metadataStale)
	if err != nil {
		return fmt.Errorf("rpm worker: querying rpm_repos: %w", err)
	}

	if !metadataStale {
		w.log.Debugw("metadata not stale, skipping", "repo_id", repoID)
		return nil
	}

	release, locked, err := tryAdvisoryLock(ctx, conn, "rpm:"+repoID)
	if err != nil {
		return fmt.Errorf("rpm worker: advisory lock for %s: %w", repoID, err)
	}

	if !locked {
		return fmt.Errorf("rpm worker: %w for %s", errRPMLockBusy, repoID)
	}

	defer release()

	var staleMarker time.Time

	err = conn.QueryRowContext(ctx, `
		SELECT metadata_stale, updated_at FROM rpm_repos WHERE repository_id = $1
	`, repoID).Scan(&metadataStale, &staleMarker)
	if err != nil {
		return fmt.Errorf("rpm worker: re-reading rpm_repos: %w", err)
	}

	if !metadataStale {
		return nil
	}

	packages, err := w.db.ListRpmPackagesForMetadata(ctx, repoID)
	if err != nil {
		return fmt.Errorf("rpm worker: loading packages: %w", err)
	}

	blobs, err := w.buildMetadata(ctx, repoID, packages)
	if err != nil {
		return err
	}

	tx, err := w.db.BeginTx(ctx)
	if err != nil {
		return fmt.Errorf("rpm worker: begin tx: %w", err)
	}
	defer func() { _ = tx.Rollback() }()

	// Rows (and their blob checksums) generated by earlier runs.
	oldSHA, err := listOldRPMMetadata(ctx, tx, repoID)
	if err != nil {
		return err
	}

	newSHA := make(map[string]string, len(blobs))

	for path, data := range blobs {
		checksum := fmt.Sprintf("%x", sha256.Sum256(data))
		newSHA[path] = checksum

		if _, err := w.blobStore.Put(ctx, bytes.NewReader(data), map[string]string{
			"path":      path,
			"format":    "rpm",
			"repo_id":   repoID,
			"base_arch": baseArch,
			"sha256":    checksum,
		}); err != nil {
			return fmt.Errorf("rpm worker: storing blob %s: %w", path, err)
		}

		if _, err := tx.ExecContext(ctx, `
			INSERT INTO repository_metadata (id, repository_id, path, blob_sha256, blob_size, last_generated)
			VALUES (gen_random_uuid(), $1, $2, $3, $4, now())
			ON CONFLICT (repository_id, path) DO UPDATE
			SET blob_sha256 = $3, blob_size = $4, last_generated = now()
		`, repoID, path, checksum, int64(len(data))); err != nil {
			return fmt.Errorf("rpm worker: updating repository_metadata for %s: %w", path, err)
		}
	}

	stalePaths, reclaim := supersededMetadata(oldSHA, newSHA)

	for _, path := range stalePaths {
		if _, err := tx.ExecContext(ctx, `DELETE FROM repository_metadata WHERE repository_id = $1 AND path = $2`, repoID, path); err != nil {
			return fmt.Errorf("rpm worker: deleting superseded repository_metadata %s: %w", path, err)
		}
	}

	result, err := tx.ExecContext(ctx, `
		UPDATE rpm_repos SET metadata_stale = false
		WHERE repository_id = $1 AND updated_at = $2
	`, repoID, staleMarker)
	if err != nil {
		return fmt.Errorf("rpm worker: clearing stale flag: %w", err)
	}

	if n, raErr := result.RowsAffected(); raErr == nil && n == 0 {
		// A concurrent upload marked the repo stale again (bumping
		// updated_at) after we captured staleMarker; leave metadata_stale
		// = true rather than clobbering it. That upload's own
		// MarkRepoStale + NotifyStale call already schedules a follow-up
		// regen that will pick up its data.
		w.log.Infow("metadata_stale changed concurrently during regeneration; leaving stale for follow-up regen",
			"repo_id", repoID)
	}

	if err := tx.Commit(); err != nil {
		return fmt.Errorf("rpm worker: commit: %w", err)
	}

	// The new set is durable: make sure a concurrent reclaim of an identical
	// blob (another repo's superseded row) did not remove one of its objects,
	// then drop the blobs nothing references any more.
	w.ensureBlobs(ctx, repoID, baseArch, blobs, newSHA)
	w.reclaimBlobs(ctx, reclaim)

	w.log.Infow("metadata regeneration complete", "repo_id", repoID, "packages", len(packages))

	return nil
}

// buildMetadata renders every generated metadata file, keyed by repo-relative path.
func (w *RPMetadataWorker) buildMetadata(ctx context.Context, repoID string, packages []pkgrpm.Package) (map[string][]byte, error) {
	revision := strconv.FormatInt(time.Now().Unix(), 10)
	ts := time.Now().Unix()

	type kind struct {
		name     string
		generate func([]pkgrpm.Package) ([]byte, error)
	}

	kinds := []kind{
		{"primary", func(p []pkgrpm.Package) ([]byte, error) { return formatrpm.GeneratePrimaryXML(p, "") }},
		{"filelists", formatrpm.GenerateFilelistsXML},
		{"other", formatrpm.GenerateOtherXML},
	}

	var (
		entries []formatrpm.RepomdData
		blobs   = make(map[string][]byte)
	)

	for _, k := range kinds {
		xmlData, err := k.generate(packages)
		if err != nil {
			return nil, fmt.Errorf("rpm worker: generating %s.xml: %w", k.name, err)
		}

		comp, err := formatrpm.CompressMetadata(xmlData)
		if err != nil {
			return nil, fmt.Errorf("rpm worker: compressing %s.xml: %w", k.name, err)
		}

		entries = append(entries, formatrpm.RepomdData{
			Type: k.name, Location: fmt.Sprintf("repodata/%s-%s.xml.gz", comp.GzSHA256, k.name),
			Checksum: comp.GzSHA256, ChecksumType: "sha256",
			Timestamp: ts, Size: comp.GzSize, OpenSize: comp.OpenSize,
		})

		blobs[fmt.Sprintf("repodata/%s-%s.xml.gz", comp.GzSHA256, k.name)] = comp.GzipData
		blobs[fmt.Sprintf("repodata/%s-%s.xml.xz", comp.XZSHA256, k.name)] = comp.XZData
	}

	// Check for comps.xml and add group entry if it exists
	compsMeta, err := w.db.GetRepoMetadataByPath(ctx, repoID, "comps.xml")
	if err == nil && compsMeta != nil {
		entries = append(entries, formatrpm.RepomdData{
			Type: "group", Location: "repodata/comps.xml",
			Checksum: compsMeta.BlobSHA256, ChecksumType: "sha256",
			Timestamp: ts, Size: compsMeta.BlobSize, OpenSize: 0,
		})
	}

	repomdXML, err := formatrpm.GenerateRepomdXML(revision, entries)
	if err != nil {
		return nil, fmt.Errorf("rpm worker: generating repomd.xml: %w", err)
	}

	blobs["repodata/repomd.xml"] = repomdXML

	if w.signer != nil {
		signature, signErr := formatrpm.SignRepomdXML(w.signer, repomdXML)
		if signErr != nil {
			w.log.Warnw("failed to sign repomd.xml", "error", signErr)
		} else {
			blobs["repodata/repomd.xml.asc"] = signature
		}

		publicKey, keyErr := formatrpm.PublicKey(w.signer)
		if keyErr != nil {
			w.log.Warnw("failed to export public key", "error", keyErr)
		} else {
			blobs["public.key"] = publicKey
		}
	}

	return blobs, nil
}

// listOldRPMMetadata returns path -> blob sha256 of the metadata rows this
// worker generates (repodata/* and public.key). comps.xml is uploaded by users
// and is deliberately excluded.
func listOldRPMMetadata(ctx context.Context, tx sq.Transaction, repoID string) (map[string]string, error) {
	rows, err := tx.QueryContext(ctx, `
		SELECT path, blob_sha256 FROM repository_metadata
		WHERE repository_id = $1 AND (path LIKE 'repodata/%' OR path = 'public.key')
	`, repoID)
	if err != nil {
		return nil, fmt.Errorf("rpm worker: listing repository_metadata: %w", err)
	}
	defer func() { _ = rows.Close() }()

	old := make(map[string]string)

	for rows.Next() {
		var path, sum string
		if err := rows.Scan(&path, &sum); err != nil {
			return nil, fmt.Errorf("rpm worker: scanning repository_metadata: %w", err)
		}

		old[path] = sum
	}

	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("rpm worker: listing repository_metadata: %w", err)
	}

	return old, nil
}

// supersededMetadata compares the previous and the freshly generated metadata
// set. stalePaths are previous paths that are no longer generated (their rows
// must go); reclaim are blob checksums that were referenced by a previous row
// that was removed or re-pointed and that the new set no longer uses (candidates
// for deletion once nothing else references them).
func supersededMetadata(oldSHA, newSHA map[string]string) ([]string, []string) {
	var stalePaths, reclaim []string

	stillUsed := make(map[string]struct{}, len(newSHA))
	for _, sum := range newSHA {
		stillUsed[sum] = struct{}{}
	}

	seen := make(map[string]struct{})

	for path, old := range oldSHA {
		cur, kept := newSHA[path]
		if !kept {
			stalePaths = append(stalePaths, path)
		}

		if old == "" || (kept && cur == old) {
			continue
		}

		if _, ok := stillUsed[old]; ok {
			continue
		}

		if _, dup := seen[old]; dup {
			continue
		}

		seen[old] = struct{}{}

		reclaim = append(reclaim, old)
	}

	sort.Strings(stalePaths)
	sort.Strings(reclaim)

	return stalePaths, reclaim
}

// ensureBlobs re-stores any blob of the committed set that is missing from the
// blob store. Under the per-blob lock this serializes with reclaimBlobs, so a
// reclaim that raced with this run's still-uncommitted rows cannot leave a
// committed row without its object.
func (w *RPMetadataWorker) ensureBlobs(ctx context.Context, repoID, baseArch string, blobs map[string][]byte, newSHA map[string]string) {
	for path, data := range blobs {
		sum := newSHA[path]

		err := storage.WithBlobLock(ctx, w.db, sum, func(ctx context.Context) error {
			_, exists, err := w.blobStore.ExistsBySHA256(ctx, sum)
			if err != nil {
				return fmt.Errorf("check blob: %w", err)
			}

			if exists {
				return nil
			}

			if _, err := w.blobStore.Put(ctx, bytes.NewReader(data), map[string]string{
				"path":      path,
				"format":    "rpm",
				"repo_id":   repoID,
				"base_arch": baseArch,
				"sha256":    sum,
			}); err != nil {
				return fmt.Errorf("restore blob: %w", err)
			}

			return nil
		})
		if err != nil {
			w.log.Errorw("rpm worker: failed to verify metadata blob", "repo_id", repoID, "path", path, "sha256", sum, "error", err)
		}
	}
}

// reclaimBlobs deletes superseded metadata blobs that no repository_metadata
// row (in any repository) and no package row references.
func (w *RPMetadataWorker) reclaimBlobs(ctx context.Context, shas []string) {
	for _, sum := range shas {
		if err := w.reclaimBlob(ctx, sum); err != nil {
			w.log.Warnw("rpm worker: failed to delete superseded metadata blob", "sha256", sum, "error", err)
		}
	}
}

// reclaimBlob runs the reference checks and the storage delete under the
// per-blob lock shared with uploaders. storage.SafeDeleteBlob is not used
// because it only counts package-table rows; generated metadata blobs are
// referenced from repository_metadata, which identical content in another
// repository (e.g. two empty repos) may share.
func (w *RPMetadataWorker) reclaimBlob(ctx context.Context, sum string) error {
	if err := storage.ValidateBlobID(sum); err != nil {
		return fmt.Errorf("invalid blob id: %w", err)
	}

	return storage.WithBlobLock(ctx, w.db, sum, func(ctx context.Context) error {
		var refs int
		if err := w.db.GetDB().QueryRowContext(ctx, `SELECT COUNT(*) FROM repository_metadata WHERE blob_sha256 = $1`, sum).Scan(&refs); err != nil {
			return fmt.Errorf("count metadata references: %w", err)
		}

		if refs > 0 {
			return nil
		}

		pkgRefs, err := w.db.BlobReferenceCount(ctx, sum)
		if err != nil {
			return fmt.Errorf("count package references: %w", err)
		}

		if pkgRefs > 0 {
			return nil
		}

		if err := w.blobStore.Delete(ctx, sum); err != nil {
			return fmt.Errorf("delete blob: %w", err)
		}

		return nil
	})
}
