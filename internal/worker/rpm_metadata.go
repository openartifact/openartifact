type RPMetadataWorker struct {
	db        sq.Database
	blobStore storage.BlobStore
	signers   gpg.Resolver
	log       *logger.Logger
	q         *regenQueue[string]
	onStale   func(repoID string)
}

func NewRPMetadataWorker(db sq.Database, blobStore storage.BlobStore, signers gpg.Resolver, log *logger.Logger, reg *metrics.Registry) *RPMetadataWorker {
	w := &RPMetadataWorker{db: db, blobStore: blobStore, signers: signers, log: log}
	w.q = newRegenQueue("rpm", log, w.Regenerate)
	w.q.setMetrics(reg)

	return w
}

func (w *RPMetadataWorker) WithDebounce(d time.Duration) *RPMetadataWorker {
	w.q.setDebounce(d)
	return w
}

// WithDrainTimeout sets how long Stop waits for pending regenerations (default
// 10s); `openartifact rebuild` raises it to wait for a whole rebuilt catalogue.
func (w *RPMetadataWorker) WithDrainTimeout(d time.Duration) *RPMetadataWorker {
	w.q.setDrainTimeout(d)
	return w
}

// WithRegenLimiter shares a concurrency limiter with the other metadata workers.
func (w *RPMetadataWorker) WithRegenLimiter(l *RegenLimiter) *RPMetadataWorker {
	w.q.setLimiter(l)
	return w
}

// signerFor returns the signer of the repository's metadata, nil when it is
// unsigned. A resolution failure aborts the regeneration: replacing signed
// metadata with unsigned metadata because of a transient error would break
// every client that verifies it.
func (w *RPMetadataWorker) signerFor(ctx context.Context, repoID string) (gpg.Signer, error) {
	if w.signers == nil {
		return nil, nil //nolint:nilnil // nil signer means unsigned
	}

	signer, err := w.signers.SignerForRepo(ctx, repoID)
	if err != nil {
		return nil, fmt.Errorf("rpm worker: resolving signing key: %w", err)
	}

	return signer, nil
}

// WithStaleHook calls fn with the repository id on every NotifyStale: the group
// repositories that list it as a member regenerate their merged metadata.
func (w *RPMetadataWorker) WithStaleHook(fn func(repoID string)) *RPMetadataWorker {
	w.onStale = fn
	return w
}

// NotifyStale schedules a coalesced regeneration of the repository's repodata.
func (w *RPMetadataWorker) NotifyStale(repoID string) {
	w.q.Notify(repoID)

	if w.onStale != nil {
		w.onStale(repoID)
	}
}

// Stop drains pending regenerations and waits for running ones (bounded).
func (w *RPMetadataWorker) Stop() {
	w.q.Stop()
}

// Regenerate synchronously rebuilds the repository's RPM metadata, including
// writing new metadata blobs and reclaiming superseded ones. NotifyStale is the
// debounced asynchronous entry point.
func (w *RPMetadataWorker) Regenerate(ctx context.Context, repoID string) error {
	conn := w.db.GetDB()

	var (
		baseArch      string
		metadataStale bool
	)

	err := conn.QueryRowContext(ctx, `
		SELECT base_arch, metadata_stale
		FROM rpm_repos
		WHERE repository_id = $1
	`, repoID).Scan(&baseArch, &metadataStale)
	if err != nil {
		return fmt.Errorf("rpm worker: querying rpm_repos: %w", err)
	}

	if !metadataStale {
		w.log.Debugw("metadata not stale, skipping", "repo_id", repoID)
		return nil
	}

	release, err := lockForRegeneration(ctx, conn, "rpm:"+repoID)
	if err != nil {
		return fmt.Errorf("rpm worker: repository %s: %w", repoID, err)
	}

	defer release()

	var staleMarker time.Time

	err = conn.QueryRowContext(ctx, `
		SELECT metadata_stale, updated_at FROM rpm_repos WHERE repository_id = $1
	`, repoID).Scan(&metadataStale, &staleMarker)
	if err != nil {
		return fmt.Errorf("rpm worker: re-reading rpm_repos: %w", err)
	}

	if !metadataStale {
		return nil
	}

	packages, err := w.PackagesForMetadata(ctx, repoID)
	if err != nil {
		return err
	}

	blobs, err := w.buildMetadata(ctx, repoID, packages)
	if err != nil {
		return err
	}

	tx, err := w.db.BeginTx(ctx)
	if err != nil {
		return fmt.Errorf("rpm worker: begin tx: %w", err)
	}
	defer func() { _ = tx.Rollback() }()

	// Rows (and their blob checksums) generated by earlier runs.
	oldSHA, err := listOldRPMMetadata(ctx, tx, repoID)
	if err != nil {
		return err
	}

	newSHA := make(map[string]string, len(blobs))
	changed := make(map[string][]byte, len(blobs))

	for path, data := range blobs {
		checksum := fmt.Sprintf("%x", sha256.Sum256(data))
		newSHA[path] = checksum

		// Identical to what the row already points at: nothing to store or
		// write, and the blob is protected by that row from reclaim.
		if oldSHA[path] == checksum {
			continue
		}

		changed[path] = data

		if _, err := w.blobStore.Put(ctx, bytes.NewReader(data), map[string]string{
			"path":      path,
			"format":    "rpm",
			"repo_id":   repoID,
			"base_arch": baseArch,
			"sha256":    checksum,
		}); err != nil {
			return fmt.Errorf("rpm worker: storing blob %s: %w", path, err)
		}

		if _, err := tx.ExecContext(ctx, `
			INSERT INTO repository_metadata (id, repository_id, path, blob_sha256, blob_size, last_generated)
			VALUES (gen_random_uuid(), $1, $2, $3, $4, now())
			ON CONFLICT (repository_id, path) DO UPDATE
			SET blob_sha256 = $3, blob_size = $4, last_generated = now()
		`, repoID, path, checksum, int64(len(data))); err != nil {
			return fmt.Errorf("rpm worker: updating repository_metadata for %s: %w", path, err)
		}
	}

	stalePaths, reclaim := supersededMetadata(oldSHA, newSHA)

	for _, path := range stalePaths {
		if _, err := tx.ExecContext(ctx, `DELETE FROM repository_metadata WHERE repository_id = $1 AND path = $2`, repoID, path); err != nil {
			return fmt.Errorf("rpm worker: deleting superseded repository_metadata %s: %w", path, err)
		}
	}

	result, err := tx.ExecContext(ctx, `
		UPDATE rpm_repos SET metadata_stale = false
		WHERE repository_id = $1 AND updated_at = $2
	`, repoID, staleMarker)
	if err != nil {
		return fmt.Errorf("rpm worker: clearing stale flag: %w", err)
	}

	if n, raErr := result.RowsAffected(); raErr == nil && n == 0 {
		// A concurrent upload marked the repo stale again (bumping
		// updated_at) after we captured staleMarker; leave metadata_stale
		// = true rather than clobbering it. That upload's own
		// MarkRepoStale + NotifyStale call already schedules a follow-up
		// regen that will pick up its data.
		w.log.Infow("metadata_stale changed concurrently during regeneration; leaving stale for follow-up regen",
			"repo_id", repoID)
	}

	if err := tx.Commit(); err != nil {
		return fmt.Errorf("rpm worker: commit: %w", err)
	}

	// The new set is durable: make sure a concurrent reclaim of an identical
	// blob (another repo's superseded row) did not remove one of its objects,
	// then drop the blobs nothing references any more.
	w.blobs().ensure(ctx, repoID, changed, newSHA, func(path, sum string) map[string]string {
		return map[string]string{
			"path":      path,
			"format":    "rpm",
			"repo_id":   repoID,
			"base_arch": baseArch,
			"sha256":    sum,
		}
	})
	w.blobs().reclaim(ctx, reclaim)

	w.log.Infow("metadata regeneration complete", "repo_id", repoID, "packages", len(packages))

	return nil
}

// PackagesForMetadata returns every package of the repository with the data its
// metadata needs, completing rows stored by older versions from their blobs.
func (w *RPMetadataWorker) PackagesForMetadata(ctx context.Context, repoID string) ([]pkgrpm.Package, error) {
	packages, err := w.db.ListRpmPackagesForMetadata(ctx, repoID)
	if err != nil {
		return nil, fmt.Errorf("rpm worker: loading packages: %w", err)
	}

	w.backfillFromBlob(ctx, repoID, packages)

	return packages, nil
}

// backfillFromBlob re-reads the headers of packages persisted before weak
// dependencies (recommends/suggests/supplements/enhances) or the installed and
// archive sizes were stored correctly, updates the in-memory packages and
// persists the result. Failures are logged and leave the package as it was
// rather than failing the regeneration.
func (w *RPMetadataWorker) backfillFromBlob(ctx context.Context, repoID string, packages []pkgrpm.Package) {
	for i := range packages {
		pkg := &packages[i]
		if pkg.WeakDepsParsed && pkg.SizesParsed {
			continue
		}

		parsed, err := w.readPackageBlob(ctx, pkg.SHA256)
		if err != nil {
			w.log.Warnw("rpm metadata backfill failed", "repo_id", repoID, "package", pkg.Name, "error", err)
			continue
		}

		pkg.Recommends, pkg.Suggests = parsed.Recommends, parsed.Suggests
		pkg.Supplements, pkg.Enhances = parsed.Supplements, parsed.Enhances
		pkg.WeakDepsParsed = true
		pkg.InstalledSize, pkg.ArchiveSize = parsed.InstalledSize, parsed.ArchiveSize
		pkg.SizesParsed = true

		extra, err := pkg.MarshalExtra()
		if err == nil {
			err = w.db.UpdateRpmPackageExtra(ctx, repoID, pkg.SHA256, extra)
		}

		if err != nil {
			w.log.Warnw("rpm metadata backfill not persisted", "repo_id", repoID, "package", pkg.Name, "error", err)
		}
	}
}

func (w *RPMetadataWorker) readPackageBlob(ctx context.Context, sha256 string) (*pkgrpm.Package, error) {
	rc, err := w.blobStore.Get(ctx, sha256)
	if err != nil {
		return nil, fmt.Errorf("opening blob: %w", err)
	}
	defer func() { _ = rc.Close() }()

	parsed, err := pkgrpm.ParseRPM(rc)
	if err != nil {
		return nil, fmt.Errorf("parsing rpm: %w", err)
	}

	return parsed, nil
}

// RegenerateStale regenerates every RPM repository flagged metadata_stale; it
// runs once at startup so migrations that invalidate metadata take effect
// without waiting for an upload.
func (w *RPMetadataWorker) RegenerateStale(ctx context.Context) {
	rows, err := w.db.GetDB().QueryContext(ctx, `SELECT repository_id FROM rpm_repos WHERE metadata_stale`)
	if err != nil {
		w.log.Warnw("listing stale rpm repos failed", "error", err)
		return
	}

	ids, err := scanStaleRepoIDs(rows)
	if err != nil {
		w.log.Warnw("listing stale rpm repos failed", "error", err)
		return
	}

	for _, id := range ids {
		if err := w.Regenerate(ctx, id); err != nil {
			w.log.Warnw("startup rpm metadata regeneration failed", "repo_id", id, "error", err)
		}
	}
}

func scanStaleRepoIDs(rows *sql.Rows) ([]string, error) {
	defer func() { _ = rows.Close() }()

	var ids []string

	for rows.Next() {
		var id string
		if err := rows.Scan(&id); err != nil {
			return nil, fmt.Errorf("scan repo id: %w", err)
		}

		ids = append(ids, id)
	}

	return ids, rows.Err()
}

// buildMetadata renders every generated metadata file, keyed by repo-relative path.
func (w *RPMetadataWorker) buildMetadata(ctx context.Context, repoID string, packages []pkgrpm.Package) (map[string][]byte, error) {
	revision := strconv.FormatInt(time.Now().Unix(), 10)
	ts := time.Now().Unix()

	type kind struct {
		name  string
		write func(io.Writer, []pkgrpm.Package) error
	}

	// Typical uncompressed XML bytes per package, used only to size the xz dictionary.
	const xmlBytesPerPackageHint = 2048

	kinds := []kind{
		{"primary", formatrpm.WritePrimaryXML},
		{"filelists", formatrpm.WriteFilelistsXML},
		{"other", formatrpm.WriteOtherXML},
	}

	var (
		entries []formatrpm.RepomdData
		blobs   = make(map[string][]byte)
	)

	for _, k := range kinds {
		// The XML streams straight into the gzip and xz encoders; the
		// uncompressed document is never held in memory.
		comp, err := formatrpm.CompressMetadataStream(func(out io.Writer) error { return k.write(out, packages) }, len(packages)*xmlBytesPerPackageHint)
		if err != nil {
			return nil, fmt.Errorf("rpm worker: generating %s.xml: %w", k.name, err)
		}

		entries = append(entries, formatrpm.RepomdData{
			Type: k.name, Location: fmt.Sprintf("repodata/%s-%s.xml.gz", comp.GzSHA256, k.name),
			Checksum: comp.GzSHA256, ChecksumType: "sha256",
			Timestamp: ts, Size: comp.GzSize, OpenSize: comp.OpenSize,
		})

		blobs[fmt.Sprintf("repodata/%s-%s.xml.gz", comp.GzSHA256, k.name)] = comp.GzipData
		blobs[fmt.Sprintf("repodata/%s-%s.xml.xz", comp.XZSHA256, k.name)] = comp.XZData
	}

	// Check for comps.xml and add group entry if it exists
	compsMeta, err := w.db.GetRepoMetadataByPath(ctx, repoID, "comps.xml")
	if err == nil && compsMeta != nil {
		entries = append(entries, formatrpm.RepomdData{
			Type: "group", Location: "repodata/comps.xml",
			Checksum: compsMeta.BlobSHA256, ChecksumType: "sha256",
			Timestamp: ts, Size: compsMeta.BlobSize, OpenSize: 0,
		})
	}

	repomdXML, err := formatrpm.GenerateRepomdXML(revision, entries)
	if err != nil {
		return nil, fmt.Errorf("rpm worker: generating repomd.xml: %w", err)
	}

	blobs["repodata/repomd.xml"] = repomdXML

	signer, err := w.signerFor(ctx, repoID)
	if err != nil {
		return nil, err
	}

	if signer != nil {
		signature, signErr := formatrpm.SignRepomdXML(signer, repomdXML)
		if signErr != nil {
			w.log.Warnw("failed to sign repomd.xml", "error", signErr)
		} else {
			blobs["repodata/repomd.xml.asc"] = signature
		}

		publicKey, keyErr := formatrpm.PublicKey(signer)
		if keyErr != nil {
			w.log.Warnw("failed to export public key", "error", keyErr)
		} else {
			blobs["public.key"] = publicKey
		}
	}

	return blobs, nil
}

// listOldRPMMetadata returns path -> blob sha256 of the metadata rows this
// worker generates (repodata/* and public.key). comps.xml is uploaded by users
// and is deliberately excluded.
func listOldRPMMetadata(ctx context.Context, tx sq.Transaction, repoID string) (map[string]string, error) {
	rows, err := tx.QueryContext(ctx, `
		SELECT path, blob_sha256 FROM repository_metadata
		WHERE repository_id = $1 AND (path LIKE 'repodata/%' OR path = 'public.key')
	`, repoID)
	if err != nil {
		return nil, fmt.Errorf("rpm worker: listing repository_metadata: %w", err)
	}
	defer func() { _ = rows.Close() }()

	old := make(map[string]string)

	for rows.Next() {
		var path, sum string
		if err := rows.Scan(&path, &sum); err != nil {
			return nil, fmt.Errorf("rpm worker: scanning repository_metadata: %w", err)
		}

		old[path] = sum
	}

	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("rpm worker: listing repository_metadata: %w", err)
	}

	return old, nil
}

// blobs returns the shared blob bookkeeping (see metadataBlobs) for this worker.
func (w *RPMetadataWorker) blobs() metadataBlobs {
	return metadataBlobs{db: w.db, store: w.blobStore, log: w.log, who: "rpm worker"}
}
