package storage

import (
	"context"
	"errors"
	"io"
	"time"
)

// ErrChunkNotFound is returned by ChunkStore.OpenChunk for a chunk that does
// not exist (never written, deleted or swept).
var ErrChunkNotFound = errors.New("upload chunk not found")

// ErrChunksNotSupported is returned by ChunkStore methods on a backend that
// cannot hold upload chunks.
var ErrChunksNotSupported = errors.New("upload chunks are not supported by this storage backend")

// ChunkStore holds the scratch objects of resumable uploads: one object per
// PATCH of an OCI blob upload. Chunks live outside the content-addressed blob
// namespace (they are never listed as blobs, deduplicated or replicated) and
// are visible to every replica that shares the blob store, which is what makes
// a chunked upload independent of the replica each request lands on.
//
// Chunk ids are UUIDs generated by the server. A chunk is written once and
// never modified; the upload session that owns it (a database row) decides
// which chunks make up the upload and in what order.
type ChunkStore interface {
	// ChunksSupported reports whether the backend can hold chunks; the other
	// methods return ErrChunksNotSupported when it cannot.
	ChunksSupported() bool

	// PutChunk streams r (any length, no seeking) into the chunk id and
	// returns the number of bytes stored. A chunk that already exists is
	// replaced. When it fails nothing is left behind under id.
	PutChunk(ctx context.Context, id string, r io.Reader) (int64, error)

	// OpenChunk reads the chunk, or returns ErrChunkNotFound.
	OpenChunk(ctx context.Context, id string) (io.ReadCloser, error)

	// DeleteChunk removes the chunk. A missing chunk is not an error.
	DeleteChunk(ctx context.Context, id string) error

	// WalkChunks calls fn with the ids of chunks last modified before
	// olderThan, in batches, until fn returns an error or the chunks run out.
	// Keys under the chunk prefix that are not chunk ids are skipped.
	WalkChunks(ctx context.Context, olderThan time.Time, fn func(ids []string) error) error
}

// ChunksFor returns the chunk store of a blob store: the store itself when it
// can hold chunks (filesystem, S3 and its relatives, Azure; shared by every
// replica that shares the blob store), otherwise a directory on this host,
// fallbackDir, which only the replica that wrote a chunk can read back.
func ChunksFor(store BlobStore, fallbackDir string) ChunkStore {
	if c, ok := store.(ChunkStore); ok && c.ChunksSupported() {
		return c
	}

	return NewDirChunkStore(fallbackDir)
}
