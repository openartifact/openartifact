package storage

import (
	"context"
	"errors"
	"io"
	"time"
)

// ErrStagingNotFound is returned by StagingStore operations for a staging
// object that does not exist (never uploaded, already promoted or expired).
var ErrStagingNotFound = errors.New("staging object not found")

// PresignGetOptions are the response overrides baked into a presigned GET URL,
// so the object store (not OpenArtifact) answers with the right file name and
// media type. Empty fields are not signed.
type PresignGetOptions struct {
	// ContentDisposition is the response-content-disposition override.
	ContentDisposition string
	// ContentType is the response-content-type override.
	ContentType string
}

// Presigner is implemented by backends that can sign direct-download URLs with
// response header overrides. BlobStore.PresignURL is the same operation
// without overrides.
type Presigner interface {
	// PresignGet returns a presigned GET URL for the blob. It returns
	// ErrPresignNotSupported when the backend cannot sign URLs.
	PresignGet(ctx context.Context, sha256 string, ttl time.Duration, opts PresignGetOptions) (string, error)
}

// PresignedPut is a presigned upload target.
type PresignedPut struct {
	// URL accepts a single HTTP PUT with the object as the body.
	URL string
	// Headers must be sent with the PUT (signed headers other than Host).
	Headers map[string]string
	// Expires is when the URL stops working.
	Expires time.Time
}

// StagingStore is implemented by backends that accept client-direct uploads
// into a staging area and can promote a verified staging object to its
// content-addressed place. Staging ids are UUIDs generated by the server.
type StagingStore interface {
	// PresignStagingPut returns a URL the client PUTs exactly size bytes to.
	// It returns ErrPresignNotSupported when the backend has no staging area.
	PresignStagingPut(ctx context.Context, id string, size int64, ttl time.Duration) (PresignedPut, error)

	// StatStaging returns the size of the staging object, or ErrStagingNotFound.
	StatStaging(ctx context.Context, id string) (int64, error)

	// OpenStaging reads the staging object, or returns ErrStagingNotFound.
	OpenStaging(ctx context.Context, id string) (io.ReadCloser, error)

	// PromoteStaging copies the staging object to the content-addressed blob
	// sha256 (a no-op when the blob already exists). The staging object is
	// left in place; the caller deletes it with DeleteStaging once the blob
	// is referenced.
	PromoteStaging(ctx context.Context, id, sha256 string, metadata map[string]string) error

	// DeleteStaging removes the staging object. A missing object is not an error.
	DeleteStaging(ctx context.Context, id string) error
}
