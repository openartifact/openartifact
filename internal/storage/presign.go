package storage

import (
	"context"
	"errors"
	"io"
	"time"
)

// ErrStagingNotFound is returned by StagingStore operations for a staging
// object that does not exist (never uploaded, already promoted or expired).
var ErrStagingNotFound = errors.New("staging object not found")

// PresignGetOptions are the response overrides baked into a presigned GET URL,
// so the object store (not OpenArtifact) answers with the right file name and
// media type. Empty fields are not signed.
type PresignGetOptions struct {
	// ContentDisposition is the response-content-disposition override.
	ContentDisposition string
	// ContentType is the response-content-type override.
	ContentType string
}

// Presigner is implemented by backends that can sign direct-download URLs with
// response header overrides. BlobStore.PresignURL is the same operation
// without overrides.
type Presigner interface {
	// PresignGet returns a presigned GET URL for the blob. It returns
	// ErrPresignNotSupported when the backend cannot sign URLs.
	PresignGet(ctx context.Context, sha256 string, ttl time.Duration, opts PresignGetOptions) (string, error)
}

// PresignedPut is a presigned upload target.
type PresignedPut struct {
	// URL accepts a single HTTP PUT with the object as the body.
	URL string
	// Headers must be sent with the PUT (signed headers other than Host).
	Headers map[string]string
	// Expires is when the URL stops working.
	Expires time.Time
}

// ErrStagingChanged is returned by OpenStaging and PromoteStaging when the
// staging object is no longer the version the caller verified: the client's
// presigned PUT URL is still valid, so it can overwrite the object at any time.
var ErrStagingChanged = errors.New("staging object changed")

// StagedObject describes a staging object as StatStaging saw it.
type StagedObject struct {
	// Size is the object size in bytes.
	Size int64
	// Version identifies the exact bytes (the object's ETag). It is passed back
	// to OpenStaging and PromoteStaging so that both fail with
	// ErrStagingChanged if the object was overwritten after it was inspected.
	Version string
}

// StagingStore is implemented by backends that accept client-direct uploads
// into a staging area and can promote a verified staging object to its
// content-addressed place. Staging ids are UUIDs generated by the server.
//
// The client keeps a working PUT URL for the whole upload TTL, so a staging
// object is never trusted by id alone: verification reads exactly the version
// StatStaging returned, and promotion copies exactly that version.
type StagingStore interface {
	// StagingSupported reports whether the backend has a staging area. The
	// remaining methods return ErrPresignNotSupported when it does not.
	StagingSupported() bool

	// PresignStagingPut returns a URL the client PUTs exactly size bytes to.
	PresignStagingPut(ctx context.Context, id string, size int64, ttl time.Duration) (PresignedPut, error)

	// StatStaging describes the staging object, or returns ErrStagingNotFound.
	StatStaging(ctx context.Context, id string) (StagedObject, error)

	// OpenStaging reads the staging object. It returns ErrStagingNotFound when
	// there is none and ErrStagingChanged when it is no longer version.
	OpenStaging(ctx context.Context, id, version string) (io.ReadCloser, error)

	// PromoteStaging copies version of the staging object to the
	// content-addressed blob sha256 (a no-op when the blob already exists). It
	// returns ErrStagingChanged, copying nothing, when the staging object is no
	// longer version. The staging object is left in place; the caller deletes
	// it with DeleteStaging once the blob is referenced.
	PromoteStaging(ctx context.Context, id, sha256, version string, metadata map[string]string) error

	// DeleteStaging removes the staging object. A missing object is not an error.
	DeleteStaging(ctx context.Context, id string) error

	// WalkStaging calls fn with the ids of staging objects last modified before
	// olderThan, in batches, until fn returns an error or the objects run out.
	// Keys under the staging prefix that are not staging ids are skipped.
	WalkStaging(ctx context.Context, olderThan time.Time, fn func(ids []string) error) error
}
