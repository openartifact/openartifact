// ErrUploadsNotSupported is returned by UploadStore methods on a backend that
// cannot hold resumable uploads.
var ErrUploadsNotSupported = errors.New("resumable uploads are not supported by this storage backend")

// ErrPromoteNotSupported is returned by UploadStore.PromoteUpload when the
// uploaded object cannot become a blob without passing through the server (the
// upload store is a host directory next to a blob store of another kind). The
// caller streams OpenUpload into BlobStore.Put instead.
var ErrPromoteNotSupported = errors.New("the upload cannot be promoted in place")

// ErrUploadDataLost means what the store holds for an upload does not match
// the position the caller recorded (object or part missing, wrong size):
// the upload cannot be completed and the client has to start again.
var ErrUploadDataLost = errors.New("upload data is missing")

// ErrUploadTooLarge means the upload outgrew what the backend can stage (parts
// or blocks of one object).
var ErrUploadTooLarge = errors.New("upload exceeds the size the storage backend can stage")

// UploadPosition is where a resumable upload stands: Offset bytes are stored,
// and State is the opaque, backend-specific token AppendUpload last handed to
// its commit callback ("" for a new upload). The caller persists both
// together, atomically, and passes them back unchanged.
type UploadPosition struct {
	State  string
	Offset int64
}

// UploadStore holds the data of resumable uploads (the chunked OCI blob
// upload): one growing object per upload, outside the content-addressed blob
// namespace (it is never listed as a blob, deduplicated or replicated), visible
// to every replica that shares the blob store.
//
// The store is not told what the bytes are; the caller hashes them as they
// stream through and keeps the running digest next to the position. The caller
// guarantees that at most one request works on an upload at a time (a lease in
// the database), so the store needs no locking of its own.
//
// Upload ids are UUIDs generated by the server.
type UploadStore interface {
	// UploadsSupported reports whether the backend can hold uploads; the other
	// methods return ErrUploadsNotSupported when it cannot.
	UploadsSupported() bool

	// AppendUpload appends the bytes of r to upload id, which stands at at.
	// Once r ended and it delivered n > 0 bytes, the store calls commit with
	// the new State and n; commit makes the new position durable (the caller
	// stores it) and returns nil on success. Only after commit returned nil does
	// the store drop what the new position supersedes, so a failure (of the
	// read, the write or commit itself) leaves the upload at the position the
	// caller still holds: the append is simply retried from there. Bytes the
	// store accepted of a failed append are overwritten by the retry. When r
	// delivers no bytes commit is not called. ErrUploadDataLost when the stored
	// data does not match at.
	AppendUpload(
		ctx context.Context,
		id string,
		at UploadPosition,
		r io.Reader,
		commit func(ctx context.Context, state string, n int64) error,
	) error

	// CompleteUpload makes the upload one object holding exactly at.Offset
	// bytes and returns its size and version (the value PromoteUpload and
	// OpenUpload check, so an object overwritten after the digest was verified
	// is refused). Calling it again for the same position is fine.
	// ErrUploadDataLost when the stored data does not match at.
	CompleteUpload(ctx context.Context, id string, at UploadPosition) (StagedObject, error)

	// PromoteUpload makes the completed upload (exactly version) the blob with
	// the given sha256, without the bytes passing through the server where the
	// backend can; an existing blob is left untouched. ErrStagingChanged when
	// the object is not version any more, ErrStagingNotFound when it is gone,
	// ErrPromoteNotSupported when the backend cannot promote in place.
	PromoteUpload(ctx context.Context, id, sha256, version string, metadata map[string]string) error

	// OpenUpload reads the completed upload, conditional on version
	// (ErrStagingChanged / ErrStagingNotFound like PromoteUpload).
	OpenUpload(ctx context.Context, id, version string) (io.ReadCloser, error)

	// DeleteUpload removes everything stored for the upload, completed or not,
	// including unfinished multipart uploads. Missing data is not an error.
	DeleteUpload(ctx context.Context, id string) error

	// WalkUploads calls fn with the ids of uploads that have stored data last
	// modified (or, for an unfinished multipart upload, started) before
	// olderThan, in batches, until fn returns an error or the uploads run out.
	// An id may be reported more than once. Entries that are not upload ids
	// are skipped.
	WalkUploads(ctx context.Context, olderThan time.Time, fn func(ids []string) error) error
}

// UploadsFor returns the upload store of a blob store: the store itself when it
// can hold uploads (filesystem, S3 and its relatives, Azure; shared by every
// replica that shares the blob store), otherwise a directory on this host,
// fallbackDir, which only the replica that wrote to it can read back.
func UploadsFor(store BlobStore, fallbackDir string) UploadStore {
	if u, ok := store.(UploadStore); ok && u.UploadsSupported() {
		return u
	}

	return NewDirUploadStore(fallbackDir)
}

// uploadPrefix is the object key prefix of uploads in object stores (next to
// blobs/ and staging/) and the directory name on a filesystem.
const uploadPrefix = "uploads/"

var errInvalidUploadID = errors.New("invalid upload id")

// validUploadID reports whether id is a canonical UUID.
func validUploadID(id string) error {
	if _, err := uuid.Parse(id); err != nil || len(id) != len(uuid.Nil.String()) {
		return fmt.Errorf("%w: %q", errInvalidUploadID, id)
	}

	return nil
}

// uploadKey is the object key of the completed upload id.
func uploadKey(id string) (string, error) {
	if err := validUploadID(id); err != nil {
		return "", err
	}

	return uploadPrefix + id, nil
}
