// Command docgen writes the generated reference pages under docs/reference
// (configuration, metrics, CLI, REST API). The pages are committed so they stay
// readable on GitHub; CI runs `docgen -check` and fails when they drift from the
// code. Run it from the repository root (`make docs-gen`).
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// outDir is where generated pages live, relative to the repository root.
const outDir = "docs/reference"

// generator returns the pages it owns: file name (relative to outDir, slash
// separated) to content. A generator owns a fixed set of names (config.md) or a
// directory prefix (api/); stale files under an owned prefix are removed by
// the writer.
type generator struct {
	name string
	// owns reports whether a path under outDir belongs to this generator.
	owns func(rel string) bool
	run  func(root string) (map[string][]byte, error)
}

//nolint:gochecknoglobals // registry filled by init functions of the generator files
var generators []generator

func register(g generator) { generators = append(generators, g) }

func main() {
	check := flag.Bool("check", false, "fail when a generated page differs from the committed one instead of writing it")
	root := flag.String("root", ".", "repository root")
	flag.Parse()

	if err := run(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, "docgen:", err)
		os.Exit(1)
	}
}

func run(root string, check bool) error {
	want := map[string][]byte{}

	for _, g := range generators {
		pages, err := g.run(root)
		if err != nil {
			return fmt.Errorf("%s: %w", g.name, err)
		}

		for rel, content := range pages {
			if !g.owns(rel) {
				return fmt.Errorf("%s: generated %q outside the paths it owns", g.name, rel)
			}

			want[rel] = content
		}
	}

	base := filepath.Join(root, outDir)

	have, err := existing(base)
	if err != nil {
		return err
	}

	var drift []string

	for rel, content := range want {
		if !bytes.Equal(have[rel], content) {
			drift = append(drift, rel)
		}
	}

	for rel := range have {
		if _, ok := want[rel]; !ok && owned(rel) {
			drift = append(drift, rel+" (stale)")
		}
	}

	slices.Sort(drift)

	if check {
		if len(drift) > 0 {
			return fmt.Errorf("generated pages are out of date: %s; run `make docs-gen` and commit docs/reference", strings.Join(drift, ", "))
		}

		return nil
	}

	for rel, content := range want {
		if err := writePage(base, rel, content); err != nil {
			return err
		}
	}

	for rel := range have {
		if _, ok := want[rel]; !ok && owned(rel) {
			if err := os.Remove(filepath.Join(base, filepath.FromSlash(rel))); err != nil {
				return err
			}
		}
	}

	return nil
}

func owned(rel string) bool {
	for _, g := range generators {
		if g.owns(rel) {
			return true
		}
	}

	return false
}

func existing(base string) (map[string][]byte, error) {
	out := map[string][]byte{}

	root, err := os.OpenRoot(base)
	if err != nil {
		if os.IsNotExist(err) {
			return out, nil
		}

		return nil, err
	}
	defer root.Close()

	fsys := root.FS()

	err = fs.WalkDir(fsys, ".", func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}

		b, err := fs.ReadFile(fsys, p)
		if err != nil {
			return err
		}

		out[p] = b

		return nil
	})

	return out, err
}

func writePage(base, rel string, content []byte) error {
	p := filepath.Join(base, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
		return err
	}

	return os.WriteFile(p, content, 0o600) // git tracks only the exec bit, so the mode does not reach the repository
}

// header is the SPDX comment every generated page starts with, followed by a
// notice naming the generator, so a reader on GitHub does not edit the page.
func header(title, source string) []byte {
	var b bytes.Buffer

	b.WriteString("<!--\nSPDX-FileCopyrightText: The OpenArtifact Authors\n\nSPDX-License-Identifier: AGPL-3.0-or-later\n-->\n\n")
	b.WriteString("<!-- Generated by `go run ./cmd/docgen` (make docs-gen) from " + source + ". Do not edit by hand. -->\n\n")
	b.WriteString("# " + title + "\n\n")

	return b.Bytes()
}
