// clientSetupFile is the generated client setup templates, relative to the
// repository root.
const clientSetupFile = "web/src/lib/clientsetup.generated.ts"

// registerClientSetup registers the snippet builder of every format. genformats
// is a standalone tool that does not run the format plugins, so it names the
// builders itself; a format missing here would be generated as the bare-URL
// fallback.
func registerClientSetup() {
	for format, b := range map[string]clientsetup.Builder{
		"npm": clientsetup.NPMBuilder, "docker": clientsetup.DockerBuilder, "pypi": clientsetup.PyPIBuilder,
		"maven": clientsetup.MavenBuilder, "helm": clientsetup.HelmBuilder, "deb": clientsetup.DebBuilder,
		"rpm": clientsetup.RPMBuilder, "pacman": clientsetup.PacmanBuilder, "nix": clientsetup.NixBuilder,
		"cargo": clientsetup.CargoBuilder, "composer": clientsetup.ComposerBuilder, "go": clientsetup.GoBuilder,
		"nuget": clientsetup.NuGetBuilder, "rubygems": clientsetup.RubyGemsBuilder, "raw": clientsetup.RawBuilder,
		"conda": clientsetup.CondaBuilder, "conan": clientsetup.ConanBuilder, "apk": clientsetup.APKBuilder,
		"terraform": clientsetup.TerraformBuilder, "ansible": clientsetup.AnsibleBuilder,
		"sbt": clientsetup.SBTBuilder, "ivy": clientsetup.IvyBuilder,
	} {
		clientsetup.Register(format, b)
	}
}

// tsString renders s as a single-quoted TypeScript string literal.
func tsString(s string) string {
	return "'" + strings.NewReplacer(
		`\`, `\\`, `'`, `\'`, "\n", `\n`, "\r", `\r`, "\t", `\t`, "\u2028", `\u2028`, "\u2029", `\u2029`,
	).Replace(s) + "'"
}

// writeSnippets renders a snippet template array at the given indent.
func writeSnippets(b *strings.Builder, indent string, snippets []clientsetup.Snippet) {
	b.WriteString("[\n")

	for _, s := range snippets {
		b.WriteString(indent + "  {\n")
		b.WriteString(indent + "    client: " + tsString(s.Client) + ",\n")
		b.WriteString(indent + "    configure: " + tsString(s.Configure) + ",\n")

		if s.Publish != "" {
			b.WriteString(indent + "    publish: " + tsString(s.Publish) + ",\n")
		}

		b.WriteString(indent + "  },\n")
	}

	b.WriteString(indent + "]")
}

// renderClientSetup returns the contents of the generated client setup file:
// the snippet and base URL templates of internal/clientsetup, for every format,
// so the web UI renders the same text the Go side serves. A proxy or group list
// is written only when it differs from the hosted one.
func renderClientSetup() []byte {
	var b strings.Builder

	b.WriteString(`// SPDX-FileCopyrightText: The OpenArtifact Authors
//
// SPDX-License-Identifier: AGPL-3.0-or-later

// Code generated by cmd/genformats from internal/clientsetup; DO NOT EDIT.
// Change a snippet in internal/clientsetup, then run ` + "`make generate`" + `.
// Templates use {{placeholders}} and {{#http}}...{{/http}} blocks; see
// renderTemplate in installCommands.ts for the substitution rules.

/** One client's configure/publish commands, as templates. */
export interface ClientSetupTemplate {
  client: string
  configure: string
  publish?: string
}

/** The templates of a format per repository type; proxy and group fall back to hosted. */
export interface ClientSetupVariants {
  hosted: readonly ClientSetupTemplate[]
  proxy?: readonly ClientSetupTemplate[]
  group?: readonly ClientSetupTemplate[]
}

/** Native repository base URL template of a format without an entry in BASE_TEMPLATES. */
export const DEFAULT_BASE_TEMPLATE = ` + tsString(clientsetup.BaseTemplate("")) + `

/** Base URL templates of the formats that do not use DEFAULT_BASE_TEMPLATE. */
export const BASE_TEMPLATES: Readonly<Record<string, string>> = {
`)

	names := repotype.Names()

	for _, n := range names {
		if t := clientsetup.BaseTemplate(n); t != clientsetup.BaseTemplate("") {
			b.WriteString("  " + n + ": " + tsString(t) + ",\n")
		}
	}

	b.WriteString("}\n\n")

	b.WriteString("/** Snippets of a format the registry does not know: the bare repository URL. */\n")
	b.WriteString("export const FALLBACK_CLIENT_SETUP: ClientSetupVariants = {\n  hosted: ")
	writeSnippets(&b, "  ", clientsetup.Templates("", repotype.Hosted))
	b.WriteString(",\n}\n\n")

	b.WriteString("/** Client setup templates of every package format. */\n")
	b.WriteString("export const CLIENT_SETUP: Readonly<Record<string, ClientSetupVariants>> = {\n")

	for _, n := range names {
		hosted := clientsetup.Templates(n, repotype.Hosted)

		b.WriteString("  " + n + ": {\n    hosted: ")
		writeSnippets(&b, "    ", hosted)
		b.WriteString(",\n")

		for _, rt := range []string{repotype.Proxy, repotype.Group} {
			if t := clientsetup.Templates(n, rt); !slices.Equal(t, hosted) {
				b.WriteString("    " + rt + ": ")
				writeSnippets(&b, "    ", t)
				b.WriteString(",\n")
			}
		}

		b.WriteString("  },\n")
	}

	b.WriteString("}\n")

	return []byte(b.String())
}
