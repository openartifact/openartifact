// Command genformats writes web/src/lib/formats.generated.ts: the package
// format ids and the policy lists the web UI needs (which formats can be proxy
// or group repositories, federated, GPG-signed, ...), generated from the
// registry in internal/repotype so the two can never drift. The file is
// committed; CI runs `genformats -check` and fails when it is stale. Run it
// from the repository root (`make generate`, or `go generate ./internal/repotype`).
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/openartifact/openartifact/internal/repotype"
)

var errStale = errors.New("generated web format constants are out of date")

// outFile is the generated file, relative to the repository root.
const outFile = "web/src/lib/formats.generated.ts"

func main() {
	check := flag.Bool("check", false, "fail when the committed file differs instead of writing it")
	root := flag.String("root", ".", "repository root")
	flag.Parse()

	if err := run(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, "genformats:", err)
		os.Exit(1)
	}
}

func run(root string, check bool) error {
	path := filepath.Join(root, filepath.FromSlash(outFile))
	want := render()

	if check {
		have, err := os.ReadFile(path)
		if err != nil {
			return err
		}

		if !bytes.Equal(have, want) {
			return fmt.Errorf("%w: run `make generate` and commit %s", errStale, outFile)
		}

		return nil
	}

	return os.WriteFile(path, want, 0o644) //nolint:gosec // a source file, not a secret
}

// tsList renders a TypeScript string array literal body.
func tsList(names []string) string {
	quoted := make([]string, len(names))
	for i, n := range names {
		quoted[i] = "'" + n + "'"
	}

	return "[" + strings.Join(quoted, ", ") + "]"
}

// render returns the contents of the generated file.
func render() []byte {
	var b strings.Builder

	b.WriteString(`// SPDX-FileCopyrightText: The OpenArtifact Authors
//
// SPDX-License-Identifier: AGPL-3.0-or-later

// Code generated by cmd/genformats from internal/repotype; DO NOT EDIT.
// Add or change a format in the Go registry, then run ` + "`make generate`" + `.

`)

	var proxy, group, federation, gpg, isolated, osv []string

	upstreams := map[string]string{}

	for _, s := range repotype.All() {
		for _, sel := range []struct {
			on   bool
			list *[]string
		}{
			{s.Proxy, &proxy}, {s.Group, &group}, {s.Federation, &federation},
			{s.Signing == repotype.SigningGPG, &gpg}, {s.Isolated, &isolated}, {s.OSVEcosystem != "", &osv},
		} {
			if sel.on {
				*sel.list = append(*sel.list, s.Name)
			}
		}

		if s.DefaultUpstream != "" {
			upstreams[s.Name] = s.DefaultUpstream
		}
	}

	b.WriteString("/** Every package format id, in picker order. */\n")
	b.WriteString("export const FORMAT_IDS = " + tsList(repotype.Names()) + " as const\n\n")
	b.WriteString("export type FormatId = (typeof FORMAT_IDS)[number]\n\n")

	for _, l := range []struct {
		name, doc string
		names     []string
	}{
		{"PROXY_FORMATS", "Formats that can be created as proxy repositories.", proxy},
		{"GROUP_FORMATS", "Formats that can be created as group repositories.", group},
		{"FEDERATION_FORMATS", "Formats whose hosted repositories can be federated.", federation},
		{"GPG_SIGNED_FORMATS", "Formats whose hosted repositories can be assigned a GPG signing key.", gpg},
		{"ISOLATED_FORMATS", "Formats served under /repos/<format>/{repo} instead of /repos/{repo}.", isolated},
		{"VULN_ECOSYSTEMS", "Formats the OSV scanner has an ecosystem for (format id = ecosystem id).", osv},
	} {
		b.WriteString("/** " + l.doc + " */\n")
		b.WriteString("export const " + l.name + ": readonly FormatId[] = " + tsList(l.names) + "\n\n")
	}

	b.WriteString("/** Upstream a proxy repository uses when none is given; formats not listed need one. */\n")
	b.WriteString("export const DEFAULT_UPSTREAMS: Readonly<Partial<Record<FormatId, string>>> = {\n")

	for _, n := range repotype.Names() {
		if u, ok := upstreams[n]; ok {
			b.WriteString("  " + n + ": '" + u + "',\n")
		}
	}

	b.WriteString("}\n")

	return []byte(b.String())
}
