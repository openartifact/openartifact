package main

import (
	"context"
	"encoding/json"
	"fmt"
	"net/http"
	"net/url"
	"path"
	"strings"
)

// Helm charts travel as the raw .tgz: OpenArtifact reads the chart name and
// version out of Chart.yaml itself, so the source's own naming (file name,
// Nexus component) never decides where a chart lands.
func init() { //nolint:gochecknoinits // every format registers itself with the importer
	registerFormat(formatDef{
		format: formatHelm, nexus: []string{"helm"}, artifactory: []string{"helm"},
		importable: importableHelm, match: matchSHA, present: presentByDigestOrFile,
		upload: helmUpload,
		remove: helmRemove,
	})
}

// presentByDigestOrFile recognises a package the destination already holds:
// by content digest when the source reports a SHA-256, otherwise by the file
// name the destination lists (Helm and RubyGems derive it from the package's
// own coordinates, which is also how their sources name the file). Sources
// that list no SHA-256 (Nexus NuGet assets carry only SHA-1 and SHA-512) would
// otherwise never be seen as present, and a re-run would fail every package
// with a conflict. The price is that a same-named copy with other bytes is
// taken for present when there is no digest to compare.
func presentByDigestOrFile(ix *targetIndex, a sourceAsset) (indexEntry, bool) {
	if a.SHA256 != "" {
		e, ok := ix.bySHA[a.SHA256]

		return e, ok
	}

	e, ok := ix.byPath[path.Base(a.Path)]

	return e, ok
}

// importableHelm selects chart archives. index.yaml is regenerated by the
// target and .prov provenance files have no counterpart on a hosted
// repository.
func importableHelm(p string) bool {
	return strings.HasSuffix(p, ".tgz")
}

func helmUpload(ctx context.Context, t *importTarget, r uploadRequest) (uploadResult, error) {
	hdr := r.Meta.header()
	hdr.Set("Content-Type", "application/gzip")

	length := r.Asset.Size
	if length <= 0 {
		length = -1
	}

	resp, err := t.send(ctx, http.MethodPost, "/repos/"+url.PathEscape(r.Dst)+"/charts", r.Body, length, hdr)
	if err != nil {
		return uploadResult{}, err
	}

	defer func() { _ = resp.Body.Close() }()

	var out struct {
		Name    string `json:"name"`
		Version string `json:"version"`
	}

	if err := json.NewDecoder(resp.Body).Decode(&out); err != nil {
		return uploadResult{}, fmt.Errorf("POST charts: decoding response: %w", err)
	}

	// The response carries no digest; the listing does.
	return t.storedResult(ctx, r.Dst, formatHelm, out.Name, func(p listedPackage) bool {
		return p.Name == out.Name && p.Version == out.Version
	})
}

// helmRemove deletes the chart the upload created. The delete endpoint
// addresses a chart by file name, which the listing gives for the package id.
func helmRemove(ctx context.Context, t *importTarget, dst string, _ sourceAsset, res uploadResult) error {
	p, ok, err := t.findStored(ctx, dst, formatHelm, "", func(p listedPackage) bool { return p.ID == res.ID })
	if err != nil {
		return err
	}

	if !ok {
		return fmt.Errorf("%w: chart %q is not listed in %q", errNotFound, res.ID, dst)
	}

	return t.deletePath(ctx, "/repos/"+url.PathEscape(dst)+"/charts/"+url.PathEscape(p.Filename))
}
