const (
	// cargoCratesIOIndex is how cargo names crates.io in the publish metadata
	// of any other registry: a dependency without a registry comes from there.
	cargoCratesIOIndex = "https://github.com/rust-lang/crates.io-index"

	// cargoMaxManifest bounds the Cargo.toml read out of a crate.
	cargoMaxManifest = 1 << 20
	// cargoMaxReadme bounds the README embedded in the publish metadata; the
	// server accepts at most 1 MiB of metadata, so a larger README is left out
	// instead of making the whole crate unimportable.
	cargoMaxReadme = 256 << 10
	// cargoMaxUnpacked bounds how much of a crate's decompressed archive is
	// scanned for the manifest.
	cargoMaxUnpacked = 1 << 30
	// cargoMaxMetadata is the server's cap on the publish metadata.
	cargoMaxMetadata = 1 << 20
)

var (
	errCargoCrate     = errors.New("unreadable crate")
	errCargoEntrySize = errors.New("archive entry too large")
	errCargoNoEntry   = errors.New("not in the archive")
	errCargoNoPackage = errors.New("the manifest has no [package] name and version")
	errCargoManifest  = errors.New("unsupported manifest")
)

func init() { //nolint:gochecknoinits // every format registers itself with the importer
	registerFormat(formatDef{
		format: formatCargo, nexus: []string{"cargo"}, artifactory: []string{"cargo"},
		importable: importableCargo, match: matchSHA,
		upload: uploadCargo,
		// The versions of a crate form one unit so that its yanked state is read
		// once and applied after each version is stored (import_fmt_cargo_yank.go).
		units: cargoUnits, transferUnit: cargoTransferUnit,
		remove: func(context.Context, *importTarget, string, sourceAsset, uploadResult) error {
			return errNoRemove(formatCargo)
		},
	})
}

// importableCargo accepts the .crate files; the sparse index, config.json and
// download stubs are regenerated by the target.
func importableCargo(p string) bool { return strings.HasSuffix(p, ".crate") }

// cargoPublish is the JSON `cargo publish` sends ahead of the crate. Field
// names follow the registry web API; the server builds the sparse index entry
// from deps, features and links.
type cargoPublish struct {
	Name          string              `json:"name"`
	Vers          string              `json:"vers"`
	Deps          []cargoDep          `json:"deps"`
	Features      map[string][]string `json:"features"`
	Authors       []string            `json:"authors"`
	Description   string              `json:"description,omitempty"`
	Documentation string              `json:"documentation,omitempty"`
	Homepage      string              `json:"homepage,omitempty"`
	Readme        string              `json:"readme,omitempty"`
	ReadmeFile    string              `json:"readme_file,omitempty"`
	Keywords      []string            `json:"keywords"`
	Categories    []string            `json:"categories"`
	License       string              `json:"license,omitempty"`
	LicenseFile   string              `json:"license_file,omitempty"`
	Repository    string              `json:"repository,omitempty"`
	Links         *string             `json:"links"`
	RustVersion   *string             `json:"rust_version"`
}

// cargoDep is one dependency in publish form: Name is the package actually
// depended on, ExplicitNameInToml the local name when it was renamed.
type cargoDep struct {
	Name               string   `json:"name"`
	VersionReq         string   `json:"version_req"`
	Features           []string `json:"features"`
	Optional           bool     `json:"optional"`
	DefaultFeatures    bool     `json:"default_features"`
	Target             *string  `json:"target"`
	Kind               string   `json:"kind"`
	Registry           *string  `json:"registry"`
	ExplicitNameInToml *string  `json:"explicit_name_in_toml"`
}

// uploadCargo publishes a crate. The publish metadata is read out of the
// crate's own Cargo.toml, so the crate is spooled; it is checked against the
// source's checksum before anything is sent, because the server cannot delete
// a published version afterwards.
func uploadCargo(ctx context.Context, t *importTarget, r uploadRequest) (uploadResult, error) {
	sum := sha256.New()

	sp, err := spool(io.TeeReader(r.Body, sum))
	if err != nil {
		return uploadResult{}, err
	}

	defer func() { _ = sp.Close() }()

	if err := cargoCheckSource(r.Asset, sp.Size, hex.EncodeToString(sum.Sum(nil))); err != nil {
		return uploadResult{}, err
	}

	// A crate that cannot be read stays unreadable: never worth a retry.
	pub, meta, err := cargoMetadata(sp, r.Asset)
	if err != nil {
		return uploadResult{}, permanent(err)
	}

	if len(meta) > cargoMaxMetadata || sp.Size > math.MaxUint32 {
		return uploadResult{}, permanent(fmt.Errorf("%w: %s-%s is too large to publish", errCargoCrate, pub.Name, pub.Vers))
	}

	prefix := binary.LittleEndian.AppendUint32(nil, uint32(len(meta))) //nolint:gosec // len(meta) <= cargoMaxMetadata, checked above
	prefix = append(prefix, meta...)
	prefix = binary.LittleEndian.AppendUint32(prefix, uint32(sp.Size)) //nolint:gosec // sp.Size <= MaxUint32, checked above

	hdr := r.Meta.header()
	hdr.Set("Content-Type", "application/octet-stream")

	resp, err := t.send(ctx, http.MethodPut, "/repos/"+url.PathEscape(r.Dst)+"/api/v1/crates/new",
		io.MultiReader(bytes.NewReader(prefix), sp.Reader()), int64(len(prefix))+sp.Size, hdr)
	if err != nil {
		return uploadResult{}, err
	}

	_ = resp.Body.Close()

	// The publish response carries no id and no digest.
	return t.storedResult(ctx, r.Dst, formatCargo, pub.Name, func(p listedPackage) bool {
		return p.Name == pub.Name && p.Version == pub.Vers
	})
}

// cargoCheckSource compares what the source delivered with what it advertised.
func cargoCheckSource(a sourceAsset, size int64, sha string) error {
	switch {
	case a.Size > 0 && size != a.Size:
		return fmt.Errorf("%w: size mismatch: source reports %d bytes, received %d (not uploaded)", errImportVerify, a.Size, size)
	case a.SHA256 != "" && sha != a.SHA256:
		return fmt.Errorf("%w: checksum mismatch: source sha256 %s, received %s (not uploaded)", errImportVerify, a.SHA256, sha)
	}

	return nil
}

// cargoMetadata builds the publish metadata of a spooled crate from the
// Cargo.toml `cargo package` put in it.
func cargoMetadata(sp *spooled, a sourceAsset) (cargoPublish, []byte, error) {
	manifestName, raw, err := cargoReadEntry(sp.Reader(), cargoMaxManifest, func(name string) bool {
		return strings.Count(name, "/") == 1 && path.Base(name) == "Cargo.toml"
	})
	if err != nil {
		return cargoPublish{}, nil, fmt.Errorf("%w: %s: reading Cargo.toml: %w", errCargoCrate, a.Path, err)
	}

	var manifest map[string]any
	if err := toml.Unmarshal(raw, &manifest); err != nil {
		return cargoPublish{}, nil, fmt.Errorf("%w: %s: parsing Cargo.toml: %w", errCargoCrate, a.Path, err)
	}

	pub, err := cargoPublishFromManifest(manifest, newCargoRegistries(a))
	if err != nil {
		return cargoPublish{}, nil, fmt.Errorf("%w: %s: %w", errCargoCrate, a.Path, err)
	}

	pkg, _ := manifest["package"].(map[string]any)
	pub.ReadmeFile, _ = pkg["readme"].(string)

	if pub.ReadmeFile != "" {
		pub.Readme, err = cargoReadme(sp, path.Dir(manifestName), pub.ReadmeFile)
		if err != nil {
			return cargoPublish{}, nil, fmt.Errorf("%w: %s: reading %s: %w", errCargoCrate, a.Path, pub.ReadmeFile, err)
		}
	}

	meta, err := json.Marshal(pub)
	if err != nil {
		return cargoPublish{}, nil, err
	}

	return pub, meta, nil
}

// cargoReadme returns the text of the README a crate declares, or "" when it is
// not in the archive or too large to embed.
func cargoReadme(sp *spooled, root, file string) (string, error) {
	want := path.Join(root, file)
	if !strings.HasPrefix(want, root+"/") {
		return "", nil
	}

	_, data, err := cargoReadEntry(sp.Reader(), cargoMaxReadme, func(name string) bool { return name == want })

	switch {
	case errors.Is(err, errCargoEntrySize), errors.Is(err, errCargoNoEntry):
		return "", nil
	case err != nil:
		return "", err
	}

	return string(data), nil
}

// cargoReadEntry returns the first regular file of a .crate (a gzip-compressed
// tar) whose cleaned name satisfies want, or errCargoNoEntry.
func cargoReadEntry(crate io.Reader, limit int64, want func(name string) bool) (string, []byte, error) {
	gz, err := gzip.NewReader(crate)
	if err != nil {
		return "", nil, err
	}

	defer func() { _ = gz.Close() }()

	tr := tar.NewReader(io.LimitReader(gz, cargoMaxUnpacked))

	for {
		hdr, err := tr.Next()
		if errors.Is(err, io.EOF) {
			return "", nil, errCargoNoEntry
		}

		if err != nil {
			return "", nil, err
		}

		name := path.Clean(hdr.Name)
		if hdr.Typeflag != tar.TypeReg || !want(name) {
			continue
		}

		data, err := io.ReadAll(io.LimitReader(tr, limit+1))
		if err != nil {
			return "", nil, err
		}

		if int64(len(data)) > limit {
			return "", nil, fmt.Errorf("%w: %s exceeds %d bytes", errCargoEntrySize, name, limit)
		}

		return name, data, nil
	}
}

// cargoRegistries tells which registry a dependency's index URL names.
type cargoRegistries struct {
	// host and repo identify the source registry: a dependency whose index
	// lives on the source host under the source repository's name is a
	// dependency on the registry the crate is being moved out of, which after
	// the move is the destination registry itself.
	host, repo string
}

func newCargoRegistries(a sourceAsset) cargoRegistries {
	u, err := url.Parse(a.URL)
	if err != nil {
		return cargoRegistries{}
	}

	return cargoRegistries{host: u.Host, repo: a.Repo}
}

// holdsSource reports whether a registry index URL is the source repository.
func (c cargoRegistries) holdsSource(index string) bool {
	u, err := url.Parse(strings.TrimPrefix(index, "sparse+"))
	if err != nil || c.host == "" || !strings.EqualFold(u.Host, c.host) {
		return false
	}

	return slices.Contains(strings.Split(u.Path, "/"), c.repo)
}

// index resolves the registry of a dependency table the way cargo publishes
// it: nil means the registry the crate is published to, a dependency with no
// registry comes from crates.io.
func (c cargoRegistries) index(dep map[string]any) (*string, error) {
	if idx, _ := dep["registry-index"].(string); idx != "" {
		if c.holdsSource(idx) {
			return nil, nil //nolint:nilnil // nil is the publish API's "this registry"
		}

		return &idx, nil
	}

	switch name, _ := dep["registry"].(string); name {
	case "", "crates-io":
		idx := cargoCratesIOIndex

		return &idx, nil
	default:
		return nil, fmt.Errorf("%w: registry %q is named without its index URL, so it cannot be resolved", errCargoManifest, name)
	}
}

// cargoPublishFromManifest maps a decoded Cargo.toml to publish metadata.
func cargoPublishFromManifest(manifest map[string]any, regs cargoRegistries) (cargoPublish, error) {
	pkg, _ := manifest["package"].(map[string]any)
	pub := cargoPublish{
		Name:          tomlString(pkg["name"]),
		Vers:          tomlString(pkg["version"]),
		Authors:       tomlStrings(pkg["authors"]),
		Description:   tomlString(pkg["description"]),
		Documentation: tomlString(pkg["documentation"]),
		Homepage:      tomlString(pkg["homepage"]),
		Keywords:      tomlStrings(pkg["keywords"]),
		Categories:    tomlStrings(pkg["categories"]),
		License:       tomlString(pkg["license"]),
		LicenseFile:   tomlString(pkg["license-file"]),
		Repository:    tomlString(pkg["repository"]),
		Features:      map[string][]string{},
	}

	if pub.Name == "" || pub.Vers == "" {
		return cargoPublish{}, errCargoNoPackage
	}

	if v := tomlString(pkg["links"]); v != "" {
		pub.Links = &v
	}

	if v := tomlString(pkg["rust-version"]); v != "" {
		pub.RustVersion = &v
	}

	features, _ := manifest["features"].(map[string]any)
	for name, v := range features {
		pub.Features[name] = tomlStrings(v)
	}

	deps, err := cargoDependencies(manifest, regs)
	if err != nil {
		return cargoPublish{}, err
	}

	pub.Deps = deps

	return pub, nil
}

// cargoDepTables are the dependency tables of a manifest or of a [target.*]
// section, in the order their dependencies are listed. Cargo also accepts the
// underscore spelling of the dev and build tables.
var cargoDepTables = []struct { //nolint:gochecknoglobals // constant table
	kind string
	keys []string
}{
	{"normal", []string{"dependencies"}},
	{"dev", []string{"dev-dependencies", "dev_dependencies"}},
	{"build", []string{"build-dependencies", "build_dependencies"}},
}

// cargoDependencies lists the dependencies of every kind, platform-specific
// ones included, in a stable order.
func cargoDependencies(manifest map[string]any, regs cargoRegistries) ([]cargoDep, error) {
	deps := []cargoDep{}

	collect := func(section map[string]any, target *string) error {
		for _, tbl := range cargoDepTables {
			for _, key := range tbl.keys {
				found, err := cargoDepTable(section[key], tbl.kind, target, regs)
				if err != nil {
					return err
				}

				deps = append(deps, found...)
			}
		}

		return nil
	}

	if err := collect(manifest, nil); err != nil {
		return nil, err
	}

	targets, _ := manifest["target"].(map[string]any)

	for _, platform := range slices.Sorted(maps.Keys(targets)) {
		section, _ := targets[platform].(map[string]any)
		if err := collect(section, &platform); err != nil {
			return nil, err
		}
	}

	return deps, nil
}

func cargoDepTable(raw any, kind string, target *string, regs cargoRegistries) ([]cargoDep, error) {
	table, _ := raw.(map[string]any)

	out := make([]cargoDep, 0, len(table))

	for _, key := range slices.Sorted(maps.Keys(table)) {
		d, err := cargoDependency(key, table[key], regs)
		if err != nil {
			return nil, fmt.Errorf("dependency %q: %w", key, err)
		}

		d.Kind = kind
		if target != nil {
			t := *target
			d.Target = &t
		}

		out = append(out, d)
	}

	return out, nil
}

// cargoDependency maps one entry of a dependency table: either a version
// requirement string or a table.
func cargoDependency(key string, spec any, regs cargoRegistries) (cargoDep, error) {
	d := cargoDep{Name: key, VersionReq: "*", Features: []string{}, DefaultFeatures: true}

	var table map[string]any

	switch s := spec.(type) {
	case string:
		d.VersionReq = s
	case map[string]any:
		table = s
	default:
		return cargoDep{}, fmt.Errorf("%w: unsupported definition of type %T", errCargoManifest, spec)
	}

	if v, ok := table["version"].(string); ok {
		d.VersionReq = v
	}

	d.Features = tomlStrings(table["features"])
	d.Optional, _ = table["optional"].(bool)

	for _, k := range []string{"default-features", "default_features"} {
		if v, ok := table[k].(bool); ok {
			d.DefaultFeatures = v
		}
	}

	if pkg, _ := table["package"].(string); pkg != "" && pkg != key {
		d.Name, d.ExplicitNameInToml = pkg, &key
	}

	var err error

	d.Registry, err = regs.index(table)

	return d, err
}

func tomlString(v any) string {
	s, _ := v.(string)

	return s
}

// tomlStrings returns the string elements of a TOML array (never nil).
func tomlStrings(v any) []string {
	items, _ := v.([]any)

	out := make([]string, 0, len(items))

	for _, it := range items {
		if s, ok := it.(string); ok {
			out = append(out, s)
		}
	}

	return out
}
