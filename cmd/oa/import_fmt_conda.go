package main

import (
	"context"
	"encoding/json"
	"fmt"
	"net/http"
	"net/url"
	"strings"
)

func init() { //nolint:gochecknoinits // every format registers itself with the importer
	registerFormat(formatDef{
		format: formatConda, nexus: []string{"conda"}, artifactory: []string{"conda"},
		importable: importableConda, match: matchSHA, present: condaPresent,
		upload: uploadConda,
		remove: removeConda,
	})
}

// importableConda accepts the package files directly under a subdir
// (<subdir>/<name>-<version>-<build>.conda or .tar.bz2). repodata.json and its
// compressed forms, channeldata.json and index.html are regenerated by the
// target.
func importableConda(p string) bool {
	subdir, file, ok := strings.Cut(p, "/")
	if !ok || subdir == "" || strings.Contains(file, "/") {
		return false
	}

	for _, ext := range []string{".conda", ".tar.bz2"} {
		if strings.HasSuffix(file, ext) && len(file) > len(ext) {
			return true
		}
	}

	return false
}

// condaPresent finds a package file the destination already holds in the same
// subdir with the same content. A file name is only unique within a subdir, so
// the digest alone is not enough: the same bytes may be published under
// several subdirs.
func condaPresent(ix *targetIndex, a sourceAsset) (indexEntry, bool) {
	subdir, file, _ := strings.Cut(a.Path, "/")

	// Most assets are new: no row bears their file name.
	if _, ok := ix.byPath[file]; !ok || a.SHA256 == "" {
		return indexEntry{}, false
	}

	for _, p := range ix.all {
		if p.Filename == file && p.SHA256 == a.SHA256 && (p.Arch == "" || p.Arch == subdir) {
			return indexEntry{ID: p.ID, SHA256: p.SHA256}, true
		}
	}

	return indexEntry{}, false
}

// uploadConda posts a package file to its subdir; the server names it after the
// X-Filename header and reports its id and stored digest.
func uploadConda(ctx context.Context, t *importTarget, r uploadRequest) (uploadResult, error) {
	// importableConda guarantees <subdir>/<package file>.
	subdir, file, _ := strings.Cut(r.Asset.Path, "/")

	length := r.Asset.Size
	if length <= 0 {
		length = -1
	}

	hdr := r.Meta.header()
	hdr.Set("Content-Type", "application/octet-stream")
	hdr.Set("X-Filename", file)

	resp, err := t.send(ctx, http.MethodPost, "/repos/"+url.PathEscape(r.Dst)+"/"+url.PathEscape(subdir), r.Body, length, hdr)
	if err != nil {
		return uploadResult{}, err
	}

	defer func() { _ = resp.Body.Close() }()

	var out struct {
		ID     string `json:"id"`
		SHA256 string `json:"sha256"`
	}

	if err := json.NewDecoder(resp.Body).Decode(&out); err != nil {
		return uploadResult{}, fmt.Errorf("POST %s: decoding response: %w", subdir, err)
	}

	return uploadResult{ID: out.ID, SHA256: strings.ToLower(out.SHA256)}, nil
}

func removeConda(ctx context.Context, t *importTarget, dst string, a sourceAsset, _ uploadResult) error {
	subdir, file, _ := strings.Cut(a.Path, "/")

	return t.deletePath(ctx, "/repos/"+url.PathEscape(dst)+"/"+url.PathEscape(subdir)+"/"+url.PathEscape(file))
}
