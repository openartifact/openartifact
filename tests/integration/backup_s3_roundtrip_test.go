func TestBackupRestoreS3RoundTrip(t *testing.T) {
	store := bsrS3Store(t)

	bsrEmptyBucket(t, store)
	t.Cleanup(func() { bsrEmptyBucket(t, store) })

	src := newBSRSide(t, "src", store)
	src.seed()
	// Drain the source's async regeneration so the blob set is stable.
	src.stopWorkers()
	// Superseded generated metadata is queued for deletion, not removed: sweep
	// it so the bucket holds exactly the objects the source still references.
	sweeper := worker.NewBlobDeletionSweeper(src.pg, tpoCopyDeleter{store}, harness.Log, 0, 500)
	if _, err := sweeper.RunOnce(t.Context()); err != nil {
		t.Fatalf("sweep queued blob deletions: %v", err)
	}

	wantBlobs := bsrBlobSizes(t, store)
	archive := src.runBackup()

	bsrEmptyBucket(t, store)

	if left := bsrListBlobs(t, store); len(left) != 0 {
		t.Fatalf("bucket not empty before restore: %d blobs", len(left))
	}

	dst := newBSRSide(t, "dst", store)
	t.Cleanup(dst.stopWorkers)

	debugLog, err := logger.New("debug", "json", "stderr")
	if err != nil {
		t.Fatalf("logger: %v", err)
	}

	engine := backup.NewEngine(dst.pg, store, debugLog, filepath.Join(t.TempDir(), "backups"))
	engine.SetRegenerator(dst.regenerator())

	if err := engine.RunRestore(t.Context(), archive); err != nil {
		t.Fatalf("RunRestore: %v", err)
	}

	t.Run("blobs", func(t *testing.T) { bsrAssertBlobsRestored(t, wantBlobs, store) })
	t.Run("go", func(t *testing.T) { bsrAssertGoRestored(t, dst) })
	t.Run("package_rows", func(t *testing.T) { bsrAssertPackageRows(t, dst) })
	t.Run("group_members", func(t *testing.T) { bsrAssertGroupRestored(t, dst) })
	t.Run("generated_metadata", func(t *testing.T) { bsrAssertGeneratedMetadata(t, dst) })
}
