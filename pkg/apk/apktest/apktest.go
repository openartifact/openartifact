// Package apktest builds .apk packages for tests: real files in the layout
// abuild writes, which [apk.ParsePackage] accepts and the apk client installs.
package apktest

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"crypto/sha1" //nolint:gosec // abuild records a SHA-1 per file in the PAX header, apk checks it
	"crypto/sha256"
	"encoding/hex"
	"path"
	"slices"
	"strconv"
	"strings"
	"testing"
	"time"

	"github.com/openartifact/openartifact/pkg/apk"
)

const (
	defaultVersion     = "1.0-r0"
	defaultArch        = "x86_64"
	defaultDescription = "test package"
	defaultLicense     = "MIT"

	// gzipOSUnix is the OS byte abuild's gzip writes.
	gzipOSUnix = 3
)

// Options describes the package [Build] makes. Only Name is required.
type Options struct {
	// Name is the package name (pkgname).
	Name string
	// Version defaults to "1.0-r0".
	Version string
	// Arch defaults to "x86_64".
	Arch string
	// Description defaults to "test package".
	Description string
	// License defaults to "MIT".
	License string
	// Origin defaults to Name.
	Origin string
	// URL is left out of the package when empty.
	URL string
	// Depends and Provides become one depend and provides line per entry.
	Depends, Provides []string
	// Files maps an install path (relative, no leading slash) to its content.
	// The default is one file, usr/share/<Name>/README. The parent directories
	// are added to the package.
	Files map[string]string
	// Sign, when set, puts an abuild signature segment in front of the control
	// segment: a .SIGN.RSA256.<key name> entry signing the control segment.
	Sign *apk.Signer
}

func (o *Options) setDefaults() {
	if o.Version == "" {
		o.Version = defaultVersion
	}

	if o.Arch == "" {
		o.Arch = defaultArch
	}

	if o.Description == "" {
		o.Description = defaultDescription
	}

	if o.License == "" {
		o.License = defaultLicense
	}

	if o.Origin == "" {
		o.Origin = o.Name
	}

	if o.Files == nil {
		o.Files = map[string]string{"usr/share/" + o.Name + "/README": o.Name + " " + o.Version + "\n"}
	}
}

// Build returns the bytes of a .apk for o: an optional signature segment, the
// control segment (.PKGINFO) and the data segment, as three gzip members. The
// output is a function of o alone. It fails the test when the options do not
// make a package that [apk.ParsePackage] accepts, for example an invalid name
// or a description with a newline.
func Build(tb testing.TB, o Options) []byte {
	tb.Helper()

	if o.Name == "" {
		tb.Fatal("apktest: Options.Name is required")
	}

	o.setDefaults()

	data, size := dataSegment(tb, o.Files)
	control := gzipTar(tb, []entry{{name: ".PKGINFO", body: pkginfo(&o, size, data)}}, false, tar.FormatUSTAR)

	var out []byte

	if o.Sign != nil {
		sig, err := o.Sign.Sign(control)
		if err != nil {
			tb.Fatalf("apktest: signing: %v", err)
		}

		out = gzipTar(tb, []entry{{name: ".SIGN.RSA256." + o.Sign.KeyName(), body: string(sig)}}, false, tar.FormatUSTAR)
	}

	out = append(append(out, control...), data...)

	if _, err := apk.ParsePackage(bytes.NewReader(out), int64(len(out))); err != nil {
		tb.Fatalf("apktest: the package is not valid: %v", err)
	}

	return out
}

// pkginfo renders the .PKGINFO of o for the data segment, which holds size
// bytes of file content.
func pkginfo(o *Options, size int64, data []byte) string {
	var b strings.Builder

	line := func(key, val string) { b.WriteString(key + " = " + val + "\n") }

	b.WriteString("# Generated by apktest\n")
	line("pkgname", o.Name)
	line("pkgver", o.Version)
	line("pkgdesc", o.Description)

	if o.URL != "" {
		line("url", o.URL)
	}

	line("builddate", "1700000000")
	line("packager", "apktest")
	line("size", strconv.FormatInt(size, 10))
	line("arch", o.Arch)
	line("origin", o.Origin)
	line("license", o.License)

	for _, d := range o.Depends {
		line("depend", d)
	}

	for _, p := range o.Provides {
		line("provides", p)
	}

	sum := sha256.Sum256(data)
	line("datahash", hex.EncodeToString(sum[:]))

	return b.String()
}

// dataSegment returns the data segment for files and the number of content
// bytes in it: directories first, as abuild lists them, then the files, each
// carrying the SHA-1 of its content in a PAX record.
func dataSegment(tb testing.TB, files map[string]string) ([]byte, int64) {
	tb.Helper()

	var (
		entries []entry
		size    int64
		dirs    = map[string]bool{}
	)

	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}

	slices.Sort(names)

	for _, name := range names {
		for dir := path.Dir(name); dir != "." && dir != "/" && !dirs[dir]; dir = path.Dir(dir) {
			dirs[dir] = true
		}
	}

	dirNames := make([]string, 0, len(dirs))
	for dir := range dirs {
		dirNames = append(dirNames, dir)
	}

	slices.Sort(dirNames)

	for _, dir := range dirNames {
		entries = append(entries, entry{name: dir + "/", dir: true})
	}

	for _, name := range names {
		sum := sha1.Sum([]byte(files[name])) //nolint:gosec // see the import
		entries = append(entries, entry{name: name, body: files[name], sha1: hex.EncodeToString(sum[:])})
		size += int64(len(files[name]))
	}

	return gzipTar(tb, entries, true, tar.FormatUnknown), size
}

// entry is one tar entry of a segment.
type entry struct {
	name string
	body string
	dir  bool
	sha1 string
}

// gzipTar returns the entries as one gzip member holding a tar stream, with
// the end-of-archive blocks only when end is set: abuild leaves them off the
// signature and control segments and keeps them on the data segment.
func gzipTar(tb testing.TB, entries []entry, end bool, format tar.Format) []byte {
	tb.Helper()

	var buf bytes.Buffer

	gw, err := gzip.NewWriterLevel(&buf, gzip.BestCompression)
	if err != nil {
		tb.Fatal(err)
	}

	gw.OS = gzipOSUnix
	tw := tar.NewWriter(gw)

	for _, e := range entries {
		hdr := &tar.Header{
			Typeflag: tar.TypeReg,
			Name:     e.name,
			Size:     int64(len(e.body)),
			Mode:     0o644,
			ModTime:  time.Unix(0, 0),
			Format:   format,
		}

		if e.dir {
			hdr.Typeflag, hdr.Mode, hdr.Size = tar.TypeDir, 0o755, 0
		}

		if e.sha1 != "" {
			hdr.PAXRecords = map[string]string{"APK-TOOLS.checksum.SHA1": e.sha1}
		}

		if err := tw.WriteHeader(hdr); err != nil {
			tb.Fatal(err)
		}

		if _, err := tw.Write([]byte(e.body)); err != nil {
			tb.Fatal(err)
		}
	}

	if end {
		err = tw.Close()
	} else {
		err = tw.Flush()
	}

	if err != nil {
		tb.Fatal(err)
	}

	if err := gw.Close(); err != nil {
		tb.Fatal(err)
	}

	return buf.Bytes()
}
