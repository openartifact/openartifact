func readDB(t *testing.T, data []byte) map[string]string {
	t.Helper()

	gz, err := gzip.NewReader(bytes.NewReader(data))
	if err != nil {
		t.Fatal(err)
	}

	out := map[string]string{}
	tr := tar.NewReader(gz)

	for {
		hdr, err := tr.Next()
		if errors.Is(err, io.EOF) {
			return out
		}

		if err != nil {
			t.Fatal(err)
		}

		body, _ := io.ReadAll(tr)
		out[hdr.Name] = string(body)
	}
}

func TestWriteDB(t *testing.T) {
	t.Parallel()

	a, b := sampleEntry(), sampleEntry()
	b.Name, b.Version = "alpha", "1-1"

	var one, two bytes.Buffer
	if err := WriteDB(&one, []DBEntry{a, b}, true); err != nil {
		t.Fatal(err)
	}

	if err := WriteDB(&two, []DBEntry{b, a}, true); err != nil {
		t.Fatal(err)
	}

	if !bytes.Equal(one.Bytes(), two.Bytes()) {
		t.Fatal("database depends on the order of the entries")
	}

	files := readDB(t, one.Bytes())
	for _, name := range []string{"hello-1:2.12-3/", "hello-1:2.12-3/desc", "hello-1:2.12-3/files", "alpha-1-1/desc", "alpha-1-1/files"} {
		if _, ok := files[name]; !ok {
			t.Errorf("member %q missing; have %v", name, files)
		}
	}

	var plain bytes.Buffer
	if err := WriteDB(&plain, []DBEntry{a}, false); err != nil {
		t.Fatal(err)
	}

	if _, ok := readDB(t, plain.Bytes())["hello-1:2.12-3/files"]; ok {
		t.Error("the plain database carries a files entry")
	}
}

