const samplePkgInfo = `# Generated by makepkg 7.0.0
pkgname = hello
pkgbase = hello
pkgver = 1:2.12-3
pkgdesc = The classic greeting
url = https://example.org/hello
builddate = 1700000000
packager = Jane <jane@example.org>
size = 4096
arch = x86_64
license = GPL-3.0-or-later
license = MIT
group = greetings
depend = glibc
depend = sh>=5
optdepend = fortune: cookies
provides = greeter=2
conflict = hi
replaces = hola
makedepend = gcc
checkdepend = check
`

type member struct {
	name string
	body string
	dir  bool
}

func buildTar(t *testing.T, members []member) []byte {
	t.Helper()

	var buf bytes.Buffer

	tw := tar.NewWriter(&buf)

	for _, m := range members {
		hdr := &tar.Header{Name: m.name, Mode: 0o644, Size: int64(len(m.body)), Typeflag: tar.TypeReg}
		if m.dir {
			hdr = &tar.Header{Name: m.name, Mode: 0o755, Typeflag: tar.TypeDir}
		}

		if err := tw.WriteHeader(hdr); err != nil {
			t.Fatal(err)
		}

		if _, err := tw.Write([]byte(m.body)); err != nil {
			t.Fatal(err)
		}
	}

	if err := tw.Close(); err != nil {
		t.Fatal(err)
	}

	return buf.Bytes()
}

func compress(t *testing.T, kind string, data []byte) []byte {
	t.Helper()

	var buf bytes.Buffer

	var w io.WriteCloser

	switch kind {
	case CompressionZstd:
		zw, err := zstd.NewWriter(&buf)
		if err != nil {
			t.Fatal(err)
		}

		w = zw
	case CompressionXZ:
		xw, err := xz.NewWriter(&buf)
		if err != nil {
			t.Fatal(err)
		}

		w = xw
	default:
		w = gzip.NewWriter(&buf)
	}

	if _, err := w.Write(data); err != nil {
		t.Fatal(err)
	}

	if err := w.Close(); err != nil {
		t.Fatal(err)
	}

	return buf.Bytes()
}

func samplePackage(t *testing.T, kind string) []byte {
	t.Helper()

	return compress(t, kind, buildTar(t, []member{
		{name: ".PKGINFO", body: samplePkgInfo},
		{name: ".BUILDINFO", body: "format = 2\n"},
		{name: ".MTREE", body: "x"},
		{name: "usr/", dir: true},
		{name: "usr/bin/", dir: true},
		{name: "usr/bin/hello", body: "#!/bin/sh\n"},
		{name: "./usr/share/doc/hello/README", body: "hi"},
	}))
}

func TestReadPackage(t *testing.T) {
	t.Parallel()

	for _, kind := range []string{CompressionZstd, CompressionXZ, CompressionGzip} {
		t.Run(kind, func(t *testing.T) {
			t.Parallel()

			pkg, err := ReadPackage(bytes.NewReader(samplePackage(t, kind)))
			if err != nil {
				t.Fatal(err)
			}

			if pkg.Compression != kind {
				t.Errorf("compression = %q", pkg.Compression)
			}

			in := pkg.Info
			if in.Name != "hello" || in.Version != "1:2.12-3" || in.Arch != "x86_64" || in.Base != "hello" {
				t.Errorf("identity: %+v", in)
			}

			if in.BuildDate != 1700000000 || in.InstalledSz != 4096 || in.Description != "The classic greeting" {
				t.Errorf("scalars: %+v", in)
			}

			if strings.Join(in.Licenses, ",") != "GPL-3.0-or-later,MIT" || strings.Join(in.Depends, ",") != "glibc,sh>=5" {
				t.Errorf("lists: %+v", in)
			}

			want := "usr/,usr/bin/,usr/bin/hello,usr/share/doc/hello/README"
			if got := strings.Join(pkg.Files, ","); got != want {
				t.Errorf("files = %q, want %q", got, want)
			}
		})
	}
}

func TestReadPackageRejects(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		data []byte
		want error
	}{
		{"empty", nil, ErrNotPackage},
		{"text", []byte("hello world, not an archive"), ErrNotPackage},
		{"bad zstd", []byte{0x28, 0xb5, 0x2f, 0xfd, 1, 2, 3, 4}, ErrNotPackage},
		{"plain tar is not compressed", buildTar(t, []member{{name: ".PKGINFO", body: samplePkgInfo}}), ErrNotPackage},
		{"no PKGINFO", compress(t, CompressionZstd, buildTar(t, []member{{name: "usr/bin/x", body: "x"}})), ErrNoPkgInfo},
		{"traversal", compress(t, CompressionZstd, buildTar(t, []member{
			{name: ".PKGINFO", body: samplePkgInfo}, {name: "usr/../../etc/passwd", body: "x"},
		})), ErrUnsafeEntry},
		{"absolute", compress(t, CompressionGzip, buildTar(t, []member{
			{name: ".PKGINFO", body: samplePkgInfo}, {name: "/etc/passwd", body: "x"},
		})), ErrUnsafeEntry},
		{"newline in name", compress(t, CompressionXZ, buildTar(t, []member{
			{name: ".PKGINFO", body: samplePkgInfo}, {name: "usr/a\nb", body: "x"},
		})), ErrUnsafeEntry},
		{"two PKGINFO", compress(t, CompressionZstd, buildTar(t, []member{
			{name: ".PKGINFO", body: samplePkgInfo}, {name: ".PKGINFO", body: samplePkgInfo},
		})), ErrInvalidField},
		{"missing name", compress(t, CompressionZstd, buildTar(t, []member{
			{name: ".PKGINFO", body: "pkgver = 1-1\narch = any\n"},
		})), ErrMissingField},
	}

	for _, tc := range tests {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()

			if _, err := ReadPackage(bytes.NewReader(tc.data)); !errors.Is(err, tc.want) {
				t.Fatalf("error = %v, want %v", err, tc.want)
			}
		})
	}
}

func TestParsePkgInfoValidation(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name string
		text string
		ok   bool
	}{
		{"minimal", "pkgname = a\npkgver = 1-1\narch = any\n", true},
		{"upper-case name", "pkgname = A\npkgver = 1-1\narch = any\n", false},
		{"leading hyphen", "pkgname = -a\npkgver = 1-1\narch = any\n", false},
		{"no release", "pkgname = a\npkgver = 1\narch = any\n", false},
		{"bad epoch", "pkgname = a\npkgver = x:1-1\narch = any\n", false},
		{"slash in version", "pkgname = a\npkgver = 1/2-1\narch = any\n", false},
		{"bad arch", "pkgname = a\npkgver = 1-1\narch = a/b\n", false},
		{"negative size", "pkgname = a\npkgver = 1-1\narch = any\nsize = -1\n", false},
		{"not utf-8", "pkgname = a\npkgver = 1-1\narch = any\npkgdesc = \xff\n", false},
	}

	for _, tc := range tests {
		_, err := ParsePkgInfo(strings.NewReader(tc.text))
		if (err == nil) != tc.ok {
			t.Errorf("%s: err = %v, want ok=%v", tc.name, err, tc.ok)
		}
	}
}

func TestFileNames(t *testing.T) {
	t.Parallel()

	info := &PkgInfo{Name: "hello", Version: "1:2.12-3", Arch: "x86_64"}
	name := PackageFileName(info.Name, info.Version, info.Arch, "zst")

	if name != "hello-1:2.12-3-x86_64.pkg.tar.zst" {
		t.Fatalf("name = %q", name)
	}

	if !FileNameMatches("hello-1-2.12-3-x86_64.pkg.tar.zst", info, "zst") {
		t.Error("FileNameMatches hyphen spelling")
	}

	if !FileNameMatches(name, info, "zst") || FileNameMatches(name, info, "xz") {
		t.Error("FileNameMatches")
	}

	if stem, ext, ok := SplitPackageFileName(name); !ok || ext != "zst" || stem != "hello-1:2.12-3-x86_64" {
		t.Errorf("split: %q %q %v", stem, ext, ok)
	}

	for _, bad := range []string{"hello.tar.zst", "hello.pkg.tar.bz2", ".pkg.tar.zst", "hello.pkg.tar.zst.sig"} {
		if _, _, ok := SplitPackageFileName(bad); ok {
			t.Errorf("%q accepted", bad)
		}
	}
}

